"""Build the Figure 4a limitations and future-work appendix."""

from __future__ import annotations

import csv
from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
TABLE_DIR = ROOT / "outputs" / "tables"
REPORT_DIR = ROOT / "reports"

FINAL_SUMMARY = TABLE_DIR / "figure4a_final_package_summary.csv"
NO_SOURCE_CLOSURE = TABLE_DIR / "figure4a_no_author_source_closure.csv"
NEXT_PROTOCOL = TABLE_DIR / "figure4a_next_trigger_protocol.csv"

OUT_CSV = TABLE_DIR / "figure4a_limitations_future_work_zh.csv"
OUT_REPORT = REPORT_DIR / "figure4a_limitations_future_work_zh.md"


def fmt(value: object, digits: int = 4) -> str:
    try:
        if pd.isna(value):
            return "nan"
        return f"{float(value):.{digits}f}"
    except (TypeError, ValueError):
        return str(value)


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8-sig") as file:
        return list(csv.DictReader(file))


def row_by(rows: list[dict[str, str]], key: str, value: str) -> dict[str, str]:
    for row in rows:
        if row.get(key) == value:
            return row
    raise KeyError(f"Missing {key}={value}")


def build_rows() -> list[dict[str, str]]:
    final = pd.read_csv(FINAL_SUMMARY)
    closure = read_rows(NO_SOURCE_CLOSURE)
    triggers = read_rows(NEXT_PROTOCOL)

    du = final[final["variant"] == "du_net"].iloc[0]
    linear = final[final["variant"] == "mf_linear_ucb_a002"].iloc[0]
    gate = row_by(closure, "item", "rerun_gate")
    author_source = row_by(closure, "item", "author_source_status")
    gap = float(linear.local_reward_weighted_w_rmse) - float(du.local_reward_weighted_w_rmse)

    trigger_names = ", ".join(row["trigger"] for row in triggers)

    return [
        {
            "category": "scope_limit",
            "limitation": "当前结果只覆盖本地实现的 DU-Net-style 与 MF-centered Linear UCB proxy 对比。",
            "evidence": "Linear UCB 的论文 feature/update protocol 未恢复，因此 comparator 不能称为 exact paper Linear UCB。",
            "implication": "结论必须限定为 proxy comparator 下的方向性结果。",
            "future_work": "若恢复 paper Linear UCB protocol，先跑 seeds 0,1,2 的最小诊断。",
        },
        {
            "category": "metric_limit",
            "limitation": "Figure 4a 的 exact w-RMSE 权重和归一化仍未完全确定。",
            "evidence": (
                f"本地 reward-weighted gap 为 {fmt(gap)}，但 conventional RMSE 为 "
                f"DU-Net {fmt(du.rmse)} vs Linear UCB proxy {fmt(linear.rmse)}，方向相反。"
            ),
            "implication": "不能只报告有利的 reward-weighted 指标。",
            "future_work": "若获得 exact w-RMSE 定义，只重算保存预测或先跑 seeds 0,1,2。",
        },
        {
            "category": "source_limit",
            "limitation": "作者源码不可用。",
            "evidence": f"author_source_status={author_source['status']}; rerun_gate={gate['status']}",
            "implication": "不能继续把作者源码恢复当成主动执行分支。",
            "future_work": "只接受非源码精确信息触发，例如 metric、split/mask、tuning 或 Linear UCB protocol。",
        },
        {
            "category": "mechanism_limit",
            "limitation": "observational entropy、DLS 和 per-cycle tuning 的论文级实现细节未公开。",
            "evidence": "本地 observational entropy 与 adaptive tuning 诊断未通过晋级门禁。",
            "implication": "继续扩大本地 entropy/tuning 网格会变成代理假设搜索。",
            "future_work": "若获得机制细节，先实现并跑 1 seed，再决定是否扩展到 seeds 0,1,2。",
        },
        {
            "category": "compute_stop_rule",
            "limitation": "更多 seed 不能解决当前主瓶颈。",
            "evidence": "20-seed 当前基线已稳定，失败候选未通过 1/3-seed gate。",
            "implication": "盲目 20-seed 会缩小置信区间，但不会改变 source/metric 阻塞。",
            "future_work": "20-seed 只允许在 source-triggered 3-seed 通过后执行。",
        },
        {
            "category": "reopen_triggers",
            "limitation": "重开条件被严格限定。",
            "evidence": f"当前允许的 trigger 为：{trigger_names}。",
            "implication": "没有这些触发项时，复现工作应停在报告层。",
            "future_work": "按 next-trigger protocol 执行最小诊断，不移动成功标准。",
        },
    ]


def write_csv(rows: list[dict[str, str]]) -> None:
    with OUT_CSV.open("w", newline="", encoding="utf-8-sig") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def markdown_table(rows: list[dict[str, str]]) -> str:
    lines = [
        "| category | limitation | evidence | implication | future work |",
        "|---|---|---|---|---|",
    ]
    for row in rows:
        lines.append(
            f"| {row['category']} | {row['limitation']} | {row['evidence']} | "
            f"{row['implication']} | {row['future_work']} |"
        )
    return "\n".join(lines)


def write_report(rows: list[dict[str, str]]) -> None:
    report = f"""# Figure 4a 限制与未来工作

Generated by `experiments/build_figure4a_limitations_future_work_zh.py`.

## 总结

在无作者源码条件下，本地 Figure 4a 结果已经达到可报告的 partial/caveated reproduction 状态，但不能声称 exact replication。剩余差距主要来自 metric、split/mask、DU-Net 机制细节和 Linear UCB comparator 协议，而不是 seed 数不足。

## 限制矩阵

{markdown_table(rows)}

## 推荐写法

最终报告应明确说明：本地 DU-Net 在 reward-weighted proxy 下相对 MF-centered Linear UCB proxy 有小幅方向性优势，但该优势低于预设阈值，且 conventional RMSE 不支持同一结论。因此，该结果支持“局部机制方向一致”，不支持“完全复现论文 Figure 4a”。

## 后续工作

后续工作只应围绕可验证的新信息展开：exact w-RMSE、MovieLens split/mask、per-cycle tuning、DU-Net entropy/DLS 或 paper Linear UCB protocol。没有这些信息时，下一步是完善报告、证据索引和限制说明，而不是继续模型实验。

CSV artifact: `{OUT_CSV.relative_to(ROOT)}`.
"""
    OUT_REPORT.write_text(report, encoding="utf-8-sig")


def main() -> None:
    TABLE_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    rows = build_rows()
    write_csv(rows)
    write_report(rows)
    print(f"Wrote {OUT_CSV}")
    print(f"Wrote {OUT_REPORT}")


if __name__ == "__main__":
    main()
