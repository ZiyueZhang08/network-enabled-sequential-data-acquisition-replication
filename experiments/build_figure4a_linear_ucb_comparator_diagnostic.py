"""Build the Figure 4a Linear UCB comparator sensitivity appendix."""

from __future__ import annotations

from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
TABLE_DIR = ROOT / "outputs" / "tables"
REPORT_DIR = ROOT / "reports"

ALPHA_SUMMARY = TABLE_DIR / "movielens_100k_svdpp_mf_linear_ucb_alpha_grid_3seeds_final_summary.csv"
MAIN_20SEED = TABLE_DIR / "movielens_100k_svdpp_figure4a_reward_weight_metric_20seeds_final_summary.csv"

OUT_CSV = TABLE_DIR / "figure4a_linear_ucb_comparator_diagnostic.csv"
OUT_REPORT = REPORT_DIR / "figure4a_linear_ucb_comparator_diagnostic.md"


def fmt(value: object, digits: int = 4) -> str:
    try:
        if pd.isna(value):
            return "nan"
        return f"{float(value):.{digits}f}"
    except (TypeError, ValueError):
        return str(value)


def alpha_value(variant: str) -> float | None:
    if variant == "mf_linear_ucb_a000":
        return 0.0
    if variant == "mf_linear_ucb_a002":
        return 0.02
    if variant == "mf_linear_ucb_a005":
        return 0.05
    if variant == "mf_linear_ucb_a010":
        return 0.10
    if variant == "mf_linear_ucb_a020":
        return 0.20
    return None


def build_rows() -> pd.DataFrame:
    alpha = pd.read_csv(ALPHA_SUMMARY)
    main = pd.read_csv(MAIN_20SEED)
    alpha_du = alpha[alpha["variant"] == "du_net"].iloc[0]
    main_du = main[main["variant"] == "du_net"].iloc[0]

    rows = []
    for row in alpha.itertuples(index=False):
        if row.policy != "mf_linear_ucb":
            continue
        a = alpha_value(str(row.variant))
        rows.append(
            {
                "source": "alpha_grid_3seed",
                "variant": row.variant,
                "alpha": a,
                "seed_count": 3,
                "w_rmse": float(row.w_rmse),
                "rmse": float(row.rmse),
                "cumulative_reward": float(row.cumulative_reward),
                "du_net_w_rmse_reference": float(alpha_du.w_rmse),
                "linear_minus_du_w_rmse_gap": float(row.w_rmse) - float(alpha_du.w_rmse),
                "is_main_proxy": row.variant == "mf_linear_ucb_a002",
            }
        )
    main_linear = main[main["variant"] == "mf_linear_ucb_a002"].iloc[0]
    rows.append(
        {
            "source": "main_confirmation_20seed",
            "variant": "mf_linear_ucb_a002",
            "alpha": 0.02,
            "seed_count": 20,
            "w_rmse": float(main_linear.w_rmse),
            "rmse": float(main_linear.rmse),
            "cumulative_reward": float(main_linear.cumulative_reward),
            "du_net_w_rmse_reference": float(main_du.w_rmse),
            "linear_minus_du_w_rmse_gap": float(main_linear.w_rmse) - float(main_du.w_rmse),
            "is_main_proxy": True,
        }
    )
    return pd.DataFrame(rows).sort_values(["source", "alpha"])


def markdown_table(rows: pd.DataFrame) -> str:
    lines = [
        "| source | variant | alpha | seeds | w-RMSE | Linear-DU gap | RMSE | reward | main proxy |",
        "|---|---|---:|---:|---:|---:|---:|---:|---|",
    ]
    for row in rows.itertuples(index=False):
        lines.append(
            f"| {row.source} | {row.variant} | {fmt(row.alpha, 3)} | {int(row.seed_count)} | "
            f"{fmt(row.w_rmse)} | {fmt(row.linear_minus_du_w_rmse_gap)} | {fmt(row.rmse)} | "
            f"{fmt(row.cumulative_reward, 1)} | {str(row.is_main_proxy).lower()} |"
        )
    return "\n".join(lines)


def write_report(rows: pd.DataFrame) -> None:
    grid = rows[rows["source"] == "alpha_grid_3seed"].copy()
    strongest = grid.sort_values("w_rmse").iloc[0]
    main3 = grid[grid["is_main_proxy"]].iloc[0]
    main20 = rows[rows["source"] == "main_confirmation_20seed"].iloc[0]
    report = f"""# Figure 4a Linear UCB Comparator Diagnostic

Generated by `experiments/build_figure4a_linear_ucb_comparator_diagnostic.py`.

## Sensitivity Table

{markdown_table(rows)}

## Decision

Keep `mf_linear_ucb_a002` as the main comparator and label it
**MF-centered Linear UCB proxy**. It is not the weakest alpha setting: in the
3-seed alpha grid, alpha `0.05` is the strongest Linear-UCB-like comparator by
w-RMSE (`{fmt(strongest.w_rmse)}`), and alpha `0.02` is close
(`{fmt(main3.w_rmse)}`). The 20-seed main confirmation gives a positive
Linear-minus-DU gap of `{fmt(main20.linear_minus_du_w_rmse_gap)}`, but this is
below the paper target gap around `0.026`.

This completes Phase 4 without moving the yardstick: the final package should
compare current DU-Net against `mf_linear_ucb_a002`, report the alpha grid as an
appendix, and avoid claiming exact paper Linear UCB implementation fidelity.

CSV artifact: `{OUT_CSV.relative_to(ROOT)}`.
"""
    OUT_REPORT.write_text(report, encoding="utf-8")


def main() -> None:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    rows = build_rows()
    rows.to_csv(OUT_CSV, index=False)
    write_report(rows)
    print(f"Wrote {OUT_CSV}")
    print(f"Wrote {OUT_REPORT}")
    print(rows.to_string(index=False))


if __name__ == "__main__":
    main()
