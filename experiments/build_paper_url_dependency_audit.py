"""Extract and classify URLs embedded in the local paper PDF."""

from __future__ import annotations

import csv
import re
from pathlib import Path

from pypdf import PdfReader


ROOT = Path(__file__).resolve().parents[1]
TABLE_DIR = ROOT / "outputs" / "tables"
REPORT_DIR = ROOT / "reports"
PDF = ROOT / "Network-Enabled Sequential Data Acquisition (1).pdf"

OUT_CSV = TABLE_DIR / "paper_url_dependency_audit.csv"
OUT_REPORT = REPORT_DIR / "paper_url_dependency_audit.md"

URL_PATTERN = re.compile(r"https?://[^\s)\]}>,;]+", flags=re.IGNORECASE)


def normalize_url(url: str) -> str:
    return url.rstrip(".,;:)")


def classify_url(url: str) -> tuple[str, str]:
    lower = url.lower()
    if "github.com/david-cortes/contextualbandits" in lower:
        return (
            "benchmark_dependency",
            "Contextual bandit comparator family; not DU-Net source or exact adapter.",
        )
    if "github.com/kwangsungjun/lrbandit" in lower:
        return (
            "benchmark_dependency",
            "Low-rank bandit comparator context; not DU-Net source/config.",
        )
    if "github.com" in lower or "gitlab" in lower or "bitbucket" in lower:
        return (
            "source_candidate_unresolved",
            "Code-hosting URL should be inspected manually if not already classified.",
        )
    if "paperswithcode" in lower:
        return (
            "literature_index",
            "Dataset/literature index context; not an author reproduction package.",
        )
    if "facebook.com" in lower:
        return (
            "background_url",
            "Platform background URL; not reproduction source.",
        )
    return (
        "general_url",
        "General paper URL; no source/supplement role identified.",
    )


def annotation_uris(page) -> list[str]:
    uris: list[str] = []
    annotations = page.get("/Annots") or []
    for annotation_ref in annotations:
        try:
            annotation = annotation_ref.get_object()
            action = annotation.get("/A") or {}
            uri = action.get("/URI")
            if uri:
                uris.append(str(uri))
        except Exception:
            continue
    return uris


def build_rows() -> list[dict[str, str]]:
    reader = PdfReader(str(PDF))
    seen: dict[str, dict[str, str]] = {}
    for page_number, page in enumerate(reader.pages, start=1):
        text = page.extract_text() or ""
        candidates = [match.group(0) for match in URL_PATTERN.finditer(text)]
        candidates.extend(annotation_uris(page))
        for raw_url in candidates:
            url = normalize_url(raw_url)
            if not url:
                continue
            category, decision = classify_url(url)
            if url not in seen:
                seen[url] = {
                    "url": url,
                    "category": category,
                    "pages": str(page_number),
                    "decision": decision,
                }
            else:
                pages = set(seen[url]["pages"].split(","))
                pages.add(str(page_number))
                seen[url]["pages"] = ",".join(sorted(pages, key=int))

    rows = sorted(seen.values(), key=lambda row: (row["category"], row["url"]))
    source_candidates = [
        row
        for row in rows
        if row["category"] == "source_candidate_unresolved"
        and "contextualbandits" not in row["url"].lower()
        and "lrbandit" not in row["url"].lower()
    ]
    rows.append(
        {
            "url": "execution_decision",
            "category": "blocked_by_missing_source" if not source_candidates else "needs_manual_followup",
            "pages": "",
            "decision": (
                "No embedded paper URL is an unclassified author source/supplement candidate."
                if not source_candidates
                else "Unclassified code-hosting URL exists and should be inspected before rerun."
            ),
        }
    )
    return rows


def write_csv(rows: list[dict[str, str]]) -> None:
    with OUT_CSV.open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def markdown_table(rows: list[dict[str, str]]) -> str:
    lines = ["| url | category | pages | decision |", "|---|---|---|---|"]
    for row in rows:
        lines.append(f"| {row['url']} | {row['category']} | {row['pages']} | {row['decision']} |")
    return "\n".join(lines)


def write_report(rows: list[dict[str, str]]) -> None:
    decision = next(row for row in rows if row["url"] == "execution_decision")
    report = f"""# Paper URL and Dependency Audit

Generated by `experiments/build_paper_url_dependency_audit.py`.

## Current Progress

The reproduction remains a strong partial reproduction. This audit extracts
URLs from the local PDF text and PDF link annotations to check whether the paper
itself embeds a source, supplement, code, or exact configuration URL that earlier
searches missed.

## URL Table

{markdown_table(rows)}

## Analysis

The extracted URLs confirm benchmark/dependency context but do not reveal an
author DU-Net source package, supplement archive, exact Figure 4a config, or
metric-definition page. The contextual bandit and low-rank bandit GitHub links
are comparator references, not the missing DU-Net backend.

## Decision

Status: `{decision['category']}`.

{decision['decision']} Continue to keep the paper-faithful rerun gate blocked
until source-backed executable details or an explicitly approved validated
dependency appears.

CSV artifact: `{OUT_CSV.relative_to(ROOT)}`.
"""
    OUT_REPORT.write_text(report, encoding="utf-8")


def main() -> None:
    TABLE_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    rows = build_rows()
    write_csv(rows)
    write_report(rows)
    print(f"Wrote {OUT_CSV}")
    print(f"Wrote {OUT_REPORT}")


if __name__ == "__main__":
    main()
