def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as file:
        for chunk in iter(lambda: file.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def artifact_rows() -> pd.DataFrame:
    rows = []
    for path in ARTIFACTS:
        exists = path.exists()
        rows.append(
            {
                "path": str(path.relative_to(ROOT)),
                "exists": exists,
                "bytes": path.stat().st_size if exists else 0,
                "sha256": sha256(path) if exists else "",
            }
        )
    return pd.DataFrame(rows)


def markdown_table(rows: pd.DataFrame) -> str:
    lines = [
        "| path | exists | bytes | sha256 |",
        "|---|---|---:|---|",
    ]
    for row in rows.itertuples(index=False):
        lines.append(
            f"| `{row.path}` | {str(row.exists).lower()} | {int(row.bytes)} | `{row.sha256}` |"
        )
    return "\n".join(lines)


def write_report(rows: pd.DataFrame) -> None:
    complete = bool(rows["exists"].all())
    report = f"""# Figure 4a Artifact Checksums

Generated by `experiments/build_figure4a_artifact_checksums.py`.

Complete: `{str(complete).lower()}`.

Use this file to verify that the final Figure 4a handoff artifacts have not
changed unexpectedly after the replication branch was closed.

{markdown_table(rows)}
"""
    OUT_REPORT.write_text(report, encoding="utf-8")


def main() -> None:
    TABLE_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    rows = artifact_rows()
    rows.to_csv(OUT_CSV, index=False)
    write_report(rows)
    print(f"Wrote {OUT_CSV}")
    print(f"Wrote {OUT_REPORT}")
    print(rows.to_string(index=False))


if __name__ == "__main__":
    main()
