"""Build a report-ready Chinese section for the Figure 4a replication result."""

from __future__ import annotations

import csv
from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
TABLE_DIR = ROOT / "outputs" / "tables"
REPORT_DIR = ROOT / "reports"

FINAL_SUMMARY = TABLE_DIR / "figure4a_final_package_summary.csv"
NO_SOURCE_CLOSURE = TABLE_DIR / "figure4a_no_author_source_closure.csv"

OUT_CSV = TABLE_DIR / "figure4a_report_ready_section_zh.csv"
OUT_REPORT = REPORT_DIR / "figure4a_report_ready_section_zh.md"

PAPER_GAP = 1.814 - 1.788


def fmt(value: object, digits: int = 4) -> str:
    try:
        if pd.isna(value):
            return "nan"
        return f"{float(value):.{digits}f}"
    except (TypeError, ValueError):
        return str(value)


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8-sig") as file:
        return list(csv.DictReader(file))


def row_by(rows: list[dict[str, str]], key: str, value: str) -> dict[str, str]:
    for row in rows:
        if row.get(key) == value:
            return row
    raise KeyError(f"Missing {key}={value}")


def build_rows() -> list[dict[str, str]]:
    final = pd.read_csv(FINAL_SUMMARY)
    closure = read_rows(NO_SOURCE_CLOSURE)
    du = final[final["variant"] == "du_net"].iloc[0]
    linear = final[final["variant"] == "mf_linear_ucb_a002"].iloc[0]
    myopic = final[final["variant"] == "myopic"].iloc[0]
    gate = row_by(closure, "item", "rerun_gate")

    gap = float(linear.local_reward_weighted_w_rmse) - float(du.local_reward_weighted_w_rmse)
    myopic_gap = float(myopic.local_reward_weighted_w_rmse) - float(du.local_reward_weighted_w_rmse)
    share = 100.0 * gap / PAPER_GAP

    return [
        {
            "section": "headline",
            "content": (
                "在无作者源码条件下，MovieLens Figure 4a 的本地复现应表述为"
                "局部、带限定的方向性复现，而不是 exact replication。"
            ),
        },
        {
            "section": "main_result",
            "content": (
                f"20 个随机初始化下，DU-Net 的 local reward-weighted w-RMSE 为 "
                f"{fmt(du.local_reward_weighted_w_rmse)}，MF-centered Linear UCB proxy 为 "
                f"{fmt(linear.local_reward_weighted_w_rmse)}，Linear-minus-DU gap 为 "
                f"{fmt(gap)}，约为论文 Figure 4a 视觉 gap 的 {fmt(share, 1)}%。"
            ),
        },
        {
            "section": "threshold",
            "content": (
                f"该 gap 为正，但低于预设次级成功阈值 +0.010；Myopic-minus-DU gap 为 "
                f"{fmt(myopic_gap)}，因此只能说明 DU-Net 在本地 reward-weighted proxy 下略优。"
            ),
        },
        {
            "section": "contradiction",
            "content": (
                f"常规 full-test RMSE 仍然反向：DU-Net 为 {fmt(du.rmse)}，"
                f"MF-centered Linear UCB proxy 为 {fmt(linear.rmse)}；因此报告中必须同时呈现"
                " conventional RMSE、sigmoid reward-weighted RMSE 和 local reward-weighted w-RMSE。"
            ),
        },
        {
            "section": "why_stop",
            "content": (
                "metric alignment、observational entropy、adaptive tuning、reward-floor adaptive "
                "以及 comparator tightening 均已完成门禁诊断，未找到可晋级的本地候选；继续扩大 seed "
                "或做无来源网格搜索只会强化代理假设，而不是更接近论文实现。"
            ),
        },
        {
            "section": "source_constraint",
            "content": (
                f"作者源码不可用，当前 rerun gate 为 {gate['status']}。后续只能在出现非源码但足够精确的"
                " w-RMSE 定义、MovieLens split/mask、per-cycle tuning 或 paper Linear UCB 协议时重开。"
            ),
        },
        {
            "section": "next_step",
            "content": (
                "下一步是报告层改进：固定 partial/caveated reproduction 口径，补充证据索引和限制说明；"
                "不再执行新的模型实验。"
            ),
        },
    ]


def write_csv(rows: list[dict[str, str]]) -> None:
    with OUT_CSV.open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def write_report(rows: list[dict[str, str]]) -> None:
    section_text = "\n\n".join(row["content"] for row in rows)
    bullets = "\n".join(f"- `{row['section']}`: {row['content']}" for row in rows)
    report = f"""# Figure 4a 报告可用结论段

Generated by `experiments/build_figure4a_report_ready_section_zh.py`.

## 可直接使用的表述

{section_text}

## 结构化要点

{bullets}

## 使用约束

- 不要写成“完全复现 Figure 4a”。
- Linear UCB 必须称为 `MF-centered Linear UCB proxy`。
- 必须同时说明 conventional RMSE 反向，否则结论会被过度包装。
- 后续模型重跑只允许在非源码精确信息触发后，从 seeds `0,1,2` 开始。

CSV artifact: `{OUT_CSV.relative_to(ROOT)}`.
"""
    OUT_REPORT.write_text(report, encoding="utf-8")


def main() -> None:
    TABLE_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    rows = build_rows()
    write_csv(rows)
    write_report(rows)
    print(f"Wrote {OUT_CSV}")
    print(f"Wrote {OUT_REPORT}")


if __name__ == "__main__":
    main()
