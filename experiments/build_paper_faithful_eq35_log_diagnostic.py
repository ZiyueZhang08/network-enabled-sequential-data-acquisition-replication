"""Compare the Eq. 3.5 log-entropy branch against the current mainline."""

from __future__ import annotations

import csv
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
REPORT_PATH = ROOT / "reports" / "paper_faithful_eq35_log_diagnostic_20260709.md"
TABLE_PATH = ROOT / "outputs" / "tables" / "paper_faithful_eq35_log_diagnostic_20260709.csv"

MAIN_SUMMARY = ROOT / "outputs" / "tables" / "paper_faithful_movielens_rank20_ep20_v4_20seeds_final_summary.csv"
FORCED_EXP_SUMMARY = (
    ROOT
    / "outputs"
    / "tables"
    / "paper_faithful_movielens_rank20_ep20_exp_comparator_20seeds_final_summary.csv"
)
LOG_DU_SUMMARY = (
    ROOT
    / "outputs"
    / "tables"
    / "paper_faithful_movielens_rank20_ep20_logeq35_dunet_20seeds_final_summary.csv"
)

METRICS = [
    "standard_mask_rmse",
    "pdf_literal_norm_rmse",
    "w_rmse",
    "reward_tail_proxy_rmse",
    "cumulative_reward",
]


def read_summary(path: Path) -> dict[str, dict[str, float | str]]:
    with path.open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    out: dict[str, dict[str, float | str]] = {}
    for row in rows:
        key = str(row["variant"])
        parsed: dict[str, float | str] = {}
        for name, value in row.items():
            try:
                parsed[name] = float(value)
            except ValueError:
                parsed[name] = value
        out[key] = parsed
    return out


def f6(value: float | str) -> str:
    return f"{float(value):.6f}"


def gap(du: dict[str, float | str], comp: dict[str, float | str], metric: str) -> float:
    return float(du[metric]) - float(comp[metric])


def write_table(
    main_du: dict[str, float | str],
    log_du: dict[str, float | str],
    main_rows: dict[str, dict[str, float | str]],
    forced_rows: dict[str, dict[str, float | str]],
) -> None:
    rows: list[dict[str, str | float]] = []
    rows.append(
        {
            "comparison": "log_du_minus_main_du",
            "metric": "standard_mask_rmse",
            "value": gap(log_du, main_du, "standard_mask_rmse"),
            "interpretation": "negative favors Eq3.5 log",
        }
    )
    rows.append(
        {
            "comparison": "log_du_minus_main_du",
            "metric": "pdf_literal_norm_rmse",
            "value": gap(log_du, main_du, "pdf_literal_norm_rmse"),
            "interpretation": "negative favors Eq3.5 log",
        }
    )
    rows.append(
        {
            "comparison": "log_du_minus_main_du",
            "metric": "cumulative_reward",
            "value": gap(log_du, main_du, "cumulative_reward"),
            "interpretation": "positive favors Eq3.5 log",
        }
    )
    for label, rows_by_variant in [("main_topk_comparators", main_rows), ("forced_exp_comparators", forced_rows)]:
        for comp_name in ("linucb_concat", "linucb_mf_interaction"):
            comp = rows_by_variant[comp_name]
            for metric in METRICS:
                rows.append(
                    {
                        "comparison": f"log_du_minus_{label}_{comp_name}",
                        "metric": metric,
                        "value": gap(log_du, comp, metric),
                        "interpretation": "negative favors DU for RMSE metrics; positive favors DU for reward",
                    }
                )
    TABLE_PATH.parent.mkdir(parents=True, exist_ok=True)
    with TABLE_PATH.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["comparison", "metric", "value", "interpretation"])
        writer.writeheader()
        writer.writerows(rows)


def build_report() -> str:
    main_rows = read_summary(MAIN_SUMMARY)
    forced_rows = read_summary(FORCED_EXP_SUMMARY)
    log_rows = read_summary(LOG_DU_SUMMARY)
    main_du = main_rows["paper_faithful_dunet"]
    log_du = log_rows["paper_faithful_dunet"]
    write_table(main_du, log_du, main_rows, forced_rows)

    lines = [
        "# Eq. 3.5 log-entropy diagnostic",
        "",
        "Generated by `experiments/build_paper_faithful_eq35_log_diagnostic.py`.",
        "",
        "## Why This Branch Was Tested",
        "",
        "The paper's Eq. 3.5 applies the acquisition utility to `log(entropy)`.",
        "The existing mainline used the Eq. 3.6 Schur-style entropy score directly.",
        "I therefore added a strict positive `log` transform and passed it into the",
        "paper-style tuning loop, then promoted the DU-Net branch to 20 seeds.",
        "",
        "## 20-seed DU-Net Comparison",
        "",
        "| branch | standard RMSE | PDF-literal RMSE | local w-RMSE | reward-tail RMSE | cumulative reward |",
        "|---|---:|---:|---:|---:|---:|",
        (
            f"| mainline direct Eq. 3.6 score | {f6(main_du['standard_mask_rmse'])} | "
            f"{f6(main_du['pdf_literal_norm_rmse'])} | {f6(main_du['w_rmse'])} | "
            f"{f6(main_du['reward_tail_proxy_rmse'])} | {f6(main_du['cumulative_reward'])} |"
        ),
        (
            f"| Eq. 3.5 log(entropy) branch | {f6(log_du['standard_mask_rmse'])} | "
            f"{f6(log_du['pdf_literal_norm_rmse'])} | {f6(log_du['w_rmse'])} | "
            f"{f6(log_du['reward_tail_proxy_rmse'])} | {f6(log_du['cumulative_reward'])} |"
        ),
        "",
        "Eq. 3.5 log minus mainline:",
        "",
        "| metric | delta | direction |",
        "|---|---:|---|",
        f"| standard RMSE | {gap(log_du, main_du, 'standard_mask_rmse'):.6f} | lower is better |",
        f"| PDF-literal RMSE | {gap(log_du, main_du, 'pdf_literal_norm_rmse'):.6f} | lower is better |",
        f"| local w-RMSE | {gap(log_du, main_du, 'w_rmse'):.6f} | lower is better |",
        f"| cumulative reward | {gap(log_du, main_du, 'cumulative_reward'):.6f} | higher is better |",
        "",
        "## Comparator Position",
        "",
        "Against the existing 20-seed top-k Linear UCB comparators, the log branch still",
        "keeps the paper-directional RMSE ordering, but the DU-Net margin narrows.",
        "",
        "| comparator | standard RMSE gap | PDF-literal RMSE gap | local w-RMSE gap | reward gap |",
        "|---|---:|---:|---:|---:|",
    ]
    for comp_name in ("linucb_concat", "linucb_mf_interaction"):
        comp = main_rows[comp_name]
        lines.append(
            f"| {comp_name} | {gap(log_du, comp, 'standard_mask_rmse'):.6f} | "
            f"{gap(log_du, comp, 'pdf_literal_norm_rmse'):.6f} | "
            f"{gap(log_du, comp, 'w_rmse'):.6f} | "
            f"{gap(log_du, comp, 'cumulative_reward'):.6f} |"
        )
    lines.extend(
        [
            "",
            "Against forced-exp Linear UCB comparators, the log branch is not robust:",
            "",
            "| comparator | standard RMSE gap | PDF-literal RMSE gap | local w-RMSE gap | reward gap |",
            "|---|---:|---:|---:|---:|",
        ]
    )
    for comp_name in ("linucb_concat", "linucb_mf_interaction"):
        comp = forced_rows[comp_name]
        lines.append(
            f"| {comp_name} | {gap(log_du, comp, 'standard_mask_rmse'):.6f} | "
            f"{gap(log_du, comp, 'pdf_literal_norm_rmse'):.6f} | "
            f"{gap(log_du, comp, 'w_rmse'):.6f} | "
            f"{gap(log_du, comp, 'cumulative_reward'):.6f} |"
        )
    lines.extend(
        [
            "",
            "## Reflection",
            "",
            "This was a legitimate paper-faithful test, but it does not shrink the",
            "Figure 4a w-RMSE/RMSE gap. It improves cumulative reward by "
            f"{gap(log_du, main_du, 'cumulative_reward'):.6f}, while worsening standard RMSE by "
            f"{gap(log_du, main_du, 'standard_mask_rmse'):.6f} and PDF-literal RMSE by "
            f"{gap(log_du, main_du, 'pdf_literal_norm_rmse'):.6f}.",
            "",
            "I therefore keep the implementation support and a dedicated config, but do not",
            "promote Eq. 3.5 log(entropy) as the current Figure 4a RMSE mainline.",
            "The current best RMSE branch remains the direct Eq. 3.6 Schur-style score.",
            "",
            "## Next Step",
            "",
            "The next faithful improvement should not be another entropy transform sweep.",
            "The useful remaining route is exact source recovery: the Figure 4a metric,",
            "MovieLens split/masks, or the paper's Linear UCB protocol. Without those, the",
            "current implementation has already tested the two plausible Eq. 3.5 readings:",
            "direct Schur-delta scoring and explicit log(entropy) scoring.",
        ]
    )
    return "\n".join(lines) + "\n"


def main() -> None:
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(build_report(), encoding="utf-8")
    print(REPORT_PATH)
    print(TABLE_PATH)


if __name__ == "__main__":
    main()
