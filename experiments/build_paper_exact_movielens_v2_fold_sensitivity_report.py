from __future__ import annotations

from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
PREFIX = "paper_exact_attempt_movielens_v2_fold_sensitivity_5seeds"
TABLE_DIR = ROOT / "outputs" / "tables"
REPORT_DIR = ROOT / "reports"
REPORT_PATH = REPORT_DIR / f"{PREFIX}.md"

METRICS_PATH = TABLE_DIR / f"{PREFIX}_metrics.csv"
SUMMARY_PATH = TABLE_DIR / f"{PREFIX}_final_summary.csv"
GAPS_PATH = TABLE_DIR / f"{PREFIX}_fold_comparator_gaps.csv"
POSITIVITY_PATH = TABLE_DIR / f"{PREFIX}_cycle_positivity.csv"


def md_table(frame: pd.DataFrame, max_rows: int | None = None) -> str:
    if frame.empty:
        return "_No rows._"
    view = frame.copy()
    if max_rows is not None:
        view = view.head(max_rows)
    for col in view.columns:
        if pd.api.types.is_numeric_dtype(view[col]):
            view[col] = view[col].map(lambda value: f"{float(value):.6g}" if pd.notna(value) else "")
        else:
            view[col] = view[col].fillna("").astype(str)

    def clean(value: object) -> str:
        return str(value).replace("|", "\\|").replace("\n", " ")

    lines = [
        "| " + " | ".join(clean(col) for col in view.columns) + " |",
        "| " + " | ".join(["---"] * len(view.columns)) + " |",
    ]
    for _, row in view.iterrows():
        lines.append("| " + " | ".join(clean(row[col]) for col in view.columns) + " |")
    return "\n".join(lines)


def read_csv(path: Path) -> pd.DataFrame:
    if not path.exists():
        return pd.DataFrame()
    return pd.read_csv(path)


def main() -> None:
    metrics = read_csv(METRICS_PATH)
    summary = read_csv(SUMMARY_PATH)
    gaps = read_csv(GAPS_PATH)
    positivity = read_csv(POSITIVITY_PATH)

    REPORT_DIR.mkdir(parents=True, exist_ok=True)

    if gaps.empty:
        gate_status = "fail_missing"
        decision = "The 5-fold sensitivity tables are missing; rerun the Phase 2.2 runner."
        coverage_text = "No coverage evidence."
    else:
        for col in ["seeds", "standard_win_rate", "reward_win_rate", "mean_standard_gap", "mean_reward_gap"]:
            gaps[col] = pd.to_numeric(gaps[col], errors="coerce")
        complete_coverage = bool((gaps["seeds"] >= 5).all() and gaps["fold"].nunique() == 5)
        rmse_stable = bool((gaps["standard_win_rate"] == 1.0).all())
        concat = gaps[gaps["comparator"] == "linucb_concat"]
        mf = gaps[gaps["comparator"] == "linucb_mf_interaction"]
        concat_reward_stable = bool(not concat.empty and (concat["reward_win_rate"] == 0.0).all())
        mf_reward_sensitive = bool(
            not mf.empty
            and float(mf["reward_win_rate"].min()) < 1.0
            and float(mf["reward_win_rate"].max()) >= 1.0
        )
        gate_status = "pass_rmse_stable_reward_sensitive" if complete_coverage and rmse_stable else "partial"
        coverage_text = (
            f"folds={gaps['fold'].nunique()}/5; "
            f"comparators={gaps['comparator'].nunique()}/2; "
            f"min_seeds_per_fold_comparator={int(gaps['seeds'].min())}; "
            f"all_standard_win_rate_1={rmse_stable}"
        )
        decision = (
            "Tau=1 DU-Net is stable on RMSE against both clean-room Linear UCB comparators across u1-u5. "
            "Reward is not stable against concat and remains comparator-sensitive against mf_interaction, "
            "so this reduces mask-overfitting concern for Figure 4a-style RMSE but cannot close exact mask or Figure 4b gates."
        )
        if concat_reward_stable:
            decision += " Against linucb_concat, DU-Net never wins final cumulative reward in this 5-seed fold audit."
        if mf_reward_sensitive:
            decision += " Against linucb_mf_interaction, reward improves on most folds but remains weaker on u1."

    coverage = (
        metrics[["fold", "variant", "seed"]]
        .drop_duplicates()
        .groupby(["fold", "variant"], as_index=False)
        .agg(seed_count=("seed", "nunique"))
        .sort_values(["fold", "variant"])
        if not metrics.empty
        else pd.DataFrame()
    )
    summary_view = (
        summary[
            [
                "fold",
                "variant",
                "seed_count",
                "standard_mask_rmse",
                "standard_mask_rmse_ci95",
                "cumulative_reward",
                "cumulative_reward_ci95",
            ]
        ].sort_values(["fold", "variant"])
        if not summary.empty
        else summary
    )

    lines = [
        "# paper_exact_attempt_movielens_v2 Fold Sensitivity Audit",
        "",
        f"- Generated by: `experiments/build_paper_exact_movielens_v2_fold_sensitivity_report.py`",
        f"- Runner: `experiments/run_paper_exact_movielens_v2_fold_sensitivity.py`",
        f"- Gate status: **{gate_status}**",
        f"- Coverage: {coverage_text}",
        "",
        "## Coverage",
        "",
        md_table(coverage),
        "",
        "## Final Fold Comparator Gaps",
        "",
        md_table(gaps),
        "",
        "## Cycle Positivity",
        "",
        md_table(positivity),
        "",
        "## Final Summary",
        "",
        md_table(summary_view),
        "",
        "## Decision",
        "",
        decision,
        "",
        "CSV artifacts:",
        "",
        f"- `{METRICS_PATH.relative_to(ROOT).as_posix()}`",
        f"- `{SUMMARY_PATH.relative_to(ROOT).as_posix()}`",
        f"- `{GAPS_PATH.relative_to(ROOT).as_posix()}`",
        f"- `{POSITIVITY_PATH.relative_to(ROOT).as_posix()}`",
    ]
    REPORT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(REPORT_PATH)


if __name__ == "__main__":
    main()
