"""Build the send-side checklist for the author/source request.

The frozen Figure 4a submission bundle already contains the copy-ready request
email. This sidecar records the outbound action, the frozen bundle identity, and
the response intake rule without rebuilding the submission bundle.
"""

from __future__ import annotations

import csv
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TABLE_DIR = ROOT / "outputs" / "tables"
REPORT_DIR = ROOT / "reports"

AUTHOR_EMAIL = TABLE_DIR / "author_source_request_email.csv"
BUNDLE_META = TABLE_DIR / "figure4a_submission_bundle_latest.csv"

OUT_CSV = TABLE_DIR / "author_source_request_send_checklist.csv"
OUT_REPORT = REPORT_DIR / "author_source_request_send_checklist.md"


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8-sig") as file:
        return list(csv.DictReader(file))


def row_by(rows: list[dict[str, str]], key: str, value: str) -> dict[str, str]:
    for row in rows:
        if row.get(key) == value:
            return row
    raise KeyError(f"Missing {key}={value}")


def read_metadata(path: Path) -> dict[str, str]:
    return {row["item"]: row["value"] for row in read_rows(path)}


def build_rows() -> list[dict[str, str]]:
    author = read_rows(AUTHOR_EMAIL)
    meta = read_metadata(BUNDLE_META)

    decision = row_by(author, "item", "execution_decision")
    subject = row_by(author, "item", "email_subject")
    p0 = row_by(author, "item", "p0_request_count")
    p1 = row_by(author, "item", "p1_request_count")

    email_ready = decision["status"] == "ready_to_send"
    return [
        {
            "step": "email_body",
            "status": "ready" if email_ready else "blocked",
            "evidence": (
                f"status={decision['status']}; subject={subject['content']}; "
                f"p0={p0['content']}; p1={p1['content']}"
            ),
            "next_action": "Use reports/author_source_request_email.md as the outbound message.",
        },
        {
            "step": "frozen_bundle_identity",
            "status": "ready",
            "evidence": (
                f"zip={meta['zip_path']}; sha256={meta['zip_sha256']}; "
                f"submission_status={meta['submission_status']}; primary_gap={meta['primary_gap']}"
            ),
            "next_action": "Optionally attach or reference this exact bundle; do not rebuild it before sending.",
        },
        {
            "step": "recipient_logging",
            "status": "external_action_required",
            "evidence": "recipient, sent date, and message id are not local artifacts yet.",
            "next_action": "After sending, record recipient/date/message-id in the project notes or reply thread.",
        },
        {
            "step": "waiting_state",
            "status": "waiting_for_external_response",
            "evidence": "No new source-backed Figure 4a material is present in the local workspace.",
            "next_action": "Do not run another local proxy sweep while waiting.",
        },
        {
            "step": "response_intake",
            "status": "defined",
            "evidence": (
                "Accepted triggers: exact w-RMSE, MovieLens split/masks, "
                "DU-Net backend or tuning protocol, or paper Linear UCB protocol."
            ),
            "next_action": "Inspect received material first; then run seeds 0,1,2 before any 20-seed promotion.",
        },
    ]


def write_csv(rows: list[dict[str, str]]) -> None:
    with OUT_CSV.open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def markdown_table(rows: list[dict[str, str]]) -> str:
    lines = [
        "| step | status | evidence | next action |",
        "|---|---|---|---|",
    ]
    for row in rows:
        lines.append(
            f"| {row['step']} | {row['status']} | {row['evidence']} | {row['next_action']} |"
        )
    return "\n".join(lines)


def write_report(rows: list[dict[str, str]]) -> None:
    email = row_by(rows, "step", "email_body")
    bundle = row_by(rows, "step", "frozen_bundle_identity")
    waiting = row_by(rows, "step", "waiting_state")
    report = f"""# Author Source Request Send Checklist

Generated by `experiments/build_author_source_request_send_checklist.py`.

## Current Progress

The Figure 4a submission bundle is frozen and the author/source request email is
ready. This sidecar records the outbound action and response-intake rule without
changing the frozen bundle.

## Checklist

{markdown_table(rows)}

## Decision

Email state: `{email['status']}`.

Bundle state: `{bundle['status']}`.

Waiting state: `{waiting['status']}`.

Send the prepared request, preserve the frozen bundle identity, and reopen model
runs only when a source-backed trigger passes intake. The first rerun remains
limited to seeds 0,1,2.

CSV artifact: `{OUT_CSV.relative_to(ROOT)}`.
"""
    OUT_REPORT.write_text(report, encoding="utf-8")


def main() -> None:
    TABLE_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    rows = build_rows()
    write_csv(rows)
    write_report(rows)
    print(f"Wrote {OUT_CSV}")
    print(f"Wrote {OUT_REPORT}")


if __name__ == "__main__":
    main()
