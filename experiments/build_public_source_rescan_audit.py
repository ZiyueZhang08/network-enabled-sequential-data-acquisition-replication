def write_csv(rows: list[dict[str, str]]) -> None:
    with OUT_CSV.open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def markdown_table(rows: list[dict[str, str]]) -> str:
    lines = [
        "| check | source/query | result | evidence | decision |",
        "|---|---|---|---|---|",
    ]
    for row in rows:
        lines.append(
            f"| {row['check_id']} | {row['source_or_query']} | {row['result']} | "
            f"{row['evidence']} | {row['decision']} |"
        )
    return "\n".join(lines)


def write_report(rows: list[dict[str, str]]) -> None:
    report = f"""# Public Source Rescan Audit

Generated by `experiments/build_public_source_rescan_audit.py`.

## Current Progress

The reproduction remains a strong partial reproduction. This audit records the
latest public source/supplement rescan for the Figure 4a faithful-rerun gate.
The goal was to find a source artifact that could supersede local proxy
assumptions.

## Rescan Table

{markdown_table(rows)}

## Analysis

The public rescan did not recover a primary DU-Net source package, supplement,
project page, exact split/config, or executable Figure 4a metric definition. It
does confirm two paper-footnote comparator dependencies, but those repositories
only bound the benchmark family; they do not reconstruct the paper's DU-Net
backend or Linear UCB adapter.

## Decision

No new faithful-rerun trigger is active. Continue to freeze the local proxy
results and run the smallest MovieLens Figure 4a 3-seed faithful diagnostic
only after a real source artifact, exact definition/config, or explicitly
approved validated dependency appears.

CSV artifact: `{OUT_CSV.relative_to(ROOT)}`.
"""
    OUT_REPORT.write_text(report, encoding="utf-8")


def main() -> None:
    TABLE_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    rows = build_rows()
    write_csv(rows)
    write_report(rows)
    print(f"Wrote {OUT_CSV}")
    print(f"Wrote {OUT_REPORT}")


if __name__ == "__main__":
    main()
