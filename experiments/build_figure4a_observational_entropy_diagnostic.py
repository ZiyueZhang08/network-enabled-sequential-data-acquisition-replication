"""Summarize the Figure 4a observational-entropy diagnostic gate."""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

TABLE_DIR = ROOT / "outputs" / "tables"
REPORT_DIR = ROOT / "reports"
SUMMARY_CSV = TABLE_DIR / "movielens_100k_svdpp_figure4a_observational_entropy_3seeds_final_summary.csv"
OUT_CSV = TABLE_DIR / "figure4a_observational_entropy_gate.csv"
OUT_REPORT = REPORT_DIR / "figure4a_observational_entropy_diagnostic.md"

BASELINE = "du_net_hybrid_topk_current"
LINEAR = "mf_linear_ucb_a002_topk"


def fmt(value: object, digits: int = 4) -> str:
    try:
        if pd.isna(value):
            return "nan"
        return f"{float(value):.{digits}f}"
    except (TypeError, ValueError):
        return str(value)


def gate_rows(summary: pd.DataFrame) -> pd.DataFrame:
    baseline = summary.loc[summary["variant"] == BASELINE].iloc[0]
    linear = summary.loc[summary["variant"] == LINEAR].iloc[0]
    rows = []
    for row in summary.itertuples(index=False):
        row_dict = row._asdict()
        w_delta = float(row.w_rmse) - float(baseline.w_rmse)
        rmse_delta = float(row.rmse) - float(baseline.rmse)
        linear_gap = float(linear.w_rmse) - float(row.w_rmse)
        passes = (
            w_delta <= -0.000001
            or (w_delta <= 0.005 and rmse_delta <= -0.015)
            or (linear_gap - (float(linear.w_rmse) - float(baseline.w_rmse)) >= 0.005)
        )
        rows.append(
            {
                "variant": row.variant,
                "policy": row.policy,
                "w_rmse": float(row.w_rmse),
                "w_rmse_delta_vs_current": w_delta,
                "rmse": float(row.rmse),
                "rmse_delta_vs_current": rmse_delta,
                "sigmoid_reward_w_rmse": float(row.sigmoid_reward_w_rmse),
                "cumulative_reward": float(row.cumulative_reward),
                "reward_delta_vs_current": float(row.cumulative_reward) - float(baseline.cumulative_reward),
                "linear_minus_variant_w_rmse_gap": linear_gap,
                "promote_to_20seed": bool(passes),
            }
        )
    return pd.DataFrame(rows)


def markdown_table(rows: pd.DataFrame) -> str:
    rows = rows.sort_values("w_rmse")
    lines = [
        "| variant | w-RMSE | delta vs current | RMSE | RMSE delta | reward | reward delta | promote |",
        "|---|---:|---:|---:|---:|---:|---:|---|",
    ]
    for row in rows.itertuples(index=False):
        lines.append(
            f"| {row.variant} | {fmt(row.w_rmse)} | {fmt(row.w_rmse_delta_vs_current)} | "
            f"{fmt(row.rmse)} | {fmt(row.rmse_delta_vs_current)} | {fmt(row.cumulative_reward, 1)} | "
            f"{fmt(row.reward_delta_vs_current, 1)} | {str(row.promote_to_20seed).lower()} |"
        )
    return "\n".join(lines)


def write_report(rows: pd.DataFrame) -> None:
    best = rows.sort_values("w_rmse").iloc[0]
    best_rmse = rows.sort_values("rmse").iloc[0]
    promoted = rows[rows["promote_to_20seed"]]
    if promoted.empty:
        decision = (
            "No observational-entropy candidate passes the Phase 2 promotion gate. "
            "Move to Phase 3 adaptive tuning instead of running any new 20-seed job."
        )
    else:
        decision = "At least one observational-entropy candidate passes the gate."
    report = f"""# Figure 4a Observational Entropy Diagnostic

Generated by `experiments/build_figure4a_observational_entropy_diagnostic.py`.

## Gate Table

{markdown_table(rows)}

## Decision

{decision}

Best primary-metric row: `{best.variant}` with w-RMSE `{fmt(best.w_rmse)}`.
Best conventional-RMSE row: `{best_rmse.variant}` with RMSE `{fmt(best_rmse.rmse)}`,
but its reward-weighted w-RMSE delta vs current is
`{fmt(best_rmse.w_rmse_delta_vs_current)}` and reward delta is
`{fmt(best_rmse.reward_delta_vs_current, 1)}`.

CSV artifact: `{OUT_CSV.relative_to(ROOT)}`.
"""
    OUT_REPORT.write_text(report, encoding="utf-8")


def main() -> None:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    summary = pd.read_csv(SUMMARY_CSV)
    rows = gate_rows(summary)
    rows.to_csv(OUT_CSV, index=False)
    write_report(rows)
    print(f"Wrote {OUT_CSV}")
    print(f"Wrote {OUT_REPORT}")
    print(rows.sort_values("w_rmse").to_string(index=False))


if __name__ == "__main__":
    main()
