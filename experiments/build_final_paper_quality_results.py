"""Build the final reproduction synthesis with the frozen benchmark caveat."""

from __future__ import annotations

import csv
from collections import Counter
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TABLE_DIR = ROOT / "outputs" / "tables"
REPORT_DIR = ROOT / "reports"


SUMMARY_CSV = TABLE_DIR / "paper_quality_current_summary.csv"
BENCHMARK_AUDIT_CSV = TABLE_DIR / "paper_benchmark_definition_audit.csv"
OUT_CSV = TABLE_DIR / "final_paper_quality_results.csv"
OUT_REPORT = REPORT_DIR / "final_paper_quality_results.md"


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def to_float(value: str) -> float:
    if value == "":
        return float("nan")
    return float(value)


def fmt(value: str | float, digits: int = 4) -> str:
    try:
        numeric = float(value)
    except (TypeError, ValueError):
        return str(value)
    if numeric != numeric:
        return ""
    return f"{numeric:.{digits}f}"


def result_verdict(row: dict[str, str]) -> str:
    reward_delta = to_float(row["reward_delta"])
    w_rmse_delta = to_float(row["w_rmse_delta"])
    setting = row["setting"].lower()
    if "ablation" in setting:
        return "mechanism diagnostic"
    if reward_delta > 0.0 and w_rmse_delta < 0.0:
        return "reproduces both reward and w-RMSE direction"
    if reward_delta <= 0.0 and w_rmse_delta < 0.0:
        return "reproduces w-RMSE direction only"
    if reward_delta > 0.0 and w_rmse_delta >= 0.0:
        return "reproduces reward direction only"
    return "does not reproduce headline direction"


def build_result_rows(summary_rows: list[dict[str, str]]) -> list[dict[str, str]]:
    out: list[dict[str, str]] = []
    for row in summary_rows:
        out.append(
            {
                "dataset": row["dataset"],
                "setting": row["setting"],
                "candidate": row["candidate"],
                "comparator": row["comparator"],
                "reward_delta": row["reward_delta"],
                "w_rmse_delta": row["w_rmse_delta"],
                "status": row["status"],
                "verdict": result_verdict(row),
                "source_table": row["source_table"],
                "note": row["note"],
            }
        )
    return out


def write_csv(rows: list[dict[str, str]], path: Path) -> None:
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def benchmark_summary(audit_rows: list[dict[str, str]]) -> dict[str, int]:
    status_counts = Counter(row["implementation_status"] for row in audit_rows)
    explicit_rows = [row for row in audit_rows if row["implementation_status"] != "unresolved"]
    target = int(audit_rows[0]["paper_target_count"]) if audit_rows else 0
    return {
        "target": target,
        "explicit": len(explicit_rows),
        "implemented": status_counts.get("implemented", 0),
        "proxy": status_counts.get("proxy", 0),
        "unresolved": status_counts.get("unresolved", 0),
        "covered_or_proxy": status_counts.get("implemented", 0) + status_counts.get("proxy", 0),
    }


def markdown_results_table(rows: list[dict[str, str]]) -> str:
    headers = [
        "dataset",
        "setting",
        "candidate",
        "comparator",
        "reward delta",
        "w-RMSE delta",
        "verdict",
    ]
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    for row in rows:
        lines.append(
            "| "
            + " | ".join(
                [
                    row["dataset"],
                    row["setting"],
                    row["candidate"],
                    row["comparator"],
                    fmt(row["reward_delta"], 2),
                    fmt(row["w_rmse_delta"], 4),
                    row["verdict"],
                ]
            )
            + " |"
        )
    return "\n".join(lines)


def write_report(
    result_rows: list[dict[str, str]],
    benchmark: dict[str, int],
    report_path: Path,
    csv_path: Path,
) -> None:
    report = f"""# Final Paper-Quality Reproduction Results

Generated by `experiments/build_final_paper_quality_results.py`.

## Final Verdict

This is a **strong partial reproduction**, not an exact DU-Net replication.

The current codebase reproduces the main empirical direction on MovieLens and
Flixster, and it turns Douban into a diagnosed sparse-network case with a
positive network-observational candidate. The remaining gap is faithfulness:
exact DU-Net architecture, exact observational entropy, exact DLS/diffusion, and
author-code-level benchmark definitions.

## Frozen Result Table

{markdown_results_table(result_rows)}

## Benchmark Claim

The benchmark claim is frozen with a caveat:

- Paper target benchmark count: {benchmark["target"]}.
- Explicitly named slots recovered from local Section 4.2.1: {benchmark["explicit"]}.
- Explicit slots implemented: {benchmark["implemented"]}.
- Explicit slots proxy-covered: {benchmark["proxy"]}.
- Explicit slots covered or proxy-covered: {benchmark["covered_or_proxy"]}.
- Paper-count slots unresolved: {benchmark["unresolved"]}.

Final wording should say: we recover and cover the 14 benchmark policies
explicitly named in the local paper text. The paper states a 16-benchmark
comparison, but two count-implied benchmark labels remain unresolved without the
original PDF figure labels, supplement, or author implementation.

## Interpretation

- MovieLens: DU-Net-style acquisition consistently improves weighted RMSE over
  myopic, but observed acquisition reward is slightly lower. This supports a
  reward-information tradeoff rather than a pure reward-maximization win.
- Flixster: this is the cleanest current reproduction. DU-Net improves both
  reward and weighted RMSE in homogeneous and heterogeneous-response settings.
- Douban: the legacy DU-Net proxy is a near tie, but network-observational
  entropy plus reliability-DLS gives a positive homogeneous candidate, and
  response-aware network observational entropy is positive under heterogeneous
  response.
- Mechanism caveat: Flixster no-network is numerically identical to DU-Net in
  the current ablation, and Douban no-DLS slightly beats reliability-DLS in one
  sparse-graph ablation. These are important boundary conditions.

## Execution Decision

No new full 20-seed rerun was launched in this step. The final synthesis uses
the already frozen 20-seed summaries and the now-frozen 14+2 benchmark caveat.
This is the safest final artifact because the current bottleneck is primary
source faithfulness, not another local convenience baseline.

## Next Step

The next meaningful branch is paper-faithful recovery, not local tuning:

1. Recover original PDF figure labels, supplement, or DU-Net author code if
   available.
2. If new dependencies are explicitly allowed, replace structural proxies with a
   validated sparse Node2Vec or ELPH implementation.
3. If paper details are recovered, rebuild exact observational entropy,
   DLS/diffusion, and author-code-level bandit adapters, then run a new final
   20-seed matrix under a new output prefix.

CSV artifact: `{csv_path.relative_to(ROOT)}`.
"""
    report_path.write_text(report, encoding="utf-8")


def main() -> None:
    TABLE_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    summary_rows = read_rows(SUMMARY_CSV)
    audit_rows = read_rows(BENCHMARK_AUDIT_CSV)
    result_rows = build_result_rows(summary_rows)
    write_csv(result_rows, OUT_CSV)
    write_report(result_rows, benchmark_summary(audit_rows), OUT_REPORT, OUT_CSV)
    print(f"Wrote {OUT_CSV}")
    print(f"Wrote {OUT_REPORT}")


if __name__ == "__main__":
    main()
