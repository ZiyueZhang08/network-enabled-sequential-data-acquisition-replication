def read_summary(path: Path) -> dict[str, dict[str, float | str]]:
    with path.open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    parsed: dict[str, dict[str, float | str]] = {}
    for row in rows:
        key = str(row["variant"])
        parsed[key] = {}
        for k, v in row.items():
            if v == "":
                parsed[key][k] = v
                continue
            try:
                parsed[key][k] = float(v)
            except ValueError:
                parsed[key][k] = v
    return parsed


def f6(value: float | str) -> str:
    return f"{float(value):.6f}"


def gap(rows: dict[str, dict[str, float | str]], comp: str, metric: str) -> float:
    return float(rows["paper_faithful_dunet"][metric]) - float(rows[comp][metric])


def write_gate_table() -> None:
    TABLE_PATH.parent.mkdir(parents=True, exist_ok=True)
    with TABLE_PATH.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["gate", "status", "evidence", "action"])
        writer.writeheader()
        writer.writerows(SOURCE_GATES)


def build_report() -> str:
    main = read_summary(MAIN_SUMMARY)
    forced = read_summary(FORCED_EXP_SUMMARY)
    v4 = read_summary(V4_USER_FEATURE_SUMMARY)

    du = main["paper_faithful_dunet"]
    old_du = v4["paper_faithful_dunet"]
    standard_delta = float(du["standard_mask_rmse"]) - float(old_du["standard_mask_rmse"])
    w_delta = float(du["w_rmse"]) - float(old_du["w_rmse"])
    reward_delta = float(du["cumulative_reward"]) - float(old_du["cumulative_reward"])

    gate_lines = [
        "| gate | status | action |",
        "|---|---|---|",
    ]
    for row in SOURCE_GATES:
        gate_lines.append(f"| {row['gate']} | {row['status']} | {row['action']} |")

    report = f"""# Paper-faithful source-gate refresh

Generated by `experiments/build_paper_faithful_source_gate_refresh_20260709.py`.

## Decision

No new source-backed trigger was found in this refresh. I therefore did not run
another 3-seed diagnostic or open a broader hyperparameter sweep. The faithful
mainline remains the rank20/ep20 run reported in
`reports/paper_faithful_figure4a_rank20_ep20_report.md`.

## Gate Status

{chr(10).join(gate_lines)}

Detailed gate evidence is written to
`outputs/tables/paper_faithful_source_gate_refresh_20260709.csv`.

## Current Figure 4a Position

Rank20/ep20 paper-faithful DU-Net:

- standard RMSE: {f6(du['standard_mask_rmse'])}
- PDF-literal normalized RMSE: {f6(du['pdf_literal_norm_rmse'])}
- local weighted RMSE: {f6(du['w_rmse'])}
- cumulative reward: {f6(du['cumulative_reward'])}

Main comparator gaps, DU-Net minus comparator:

| comparator | standard RMSE gap | PDF-literal RMSE gap | local weighted RMSE gap | cumulative reward gap |
|---|---:|---:|---:|---:|
| Linear UCB concat | {gap(main, 'linucb_concat', 'standard_mask_rmse'):.6f} | {gap(main, 'linucb_concat', 'pdf_literal_norm_rmse'):.6f} | {gap(main, 'linucb_concat', 'w_rmse'):.6f} | {gap(main, 'linucb_concat', 'cumulative_reward'):.6f} |
| Linear UCB MF | {gap(main, 'linucb_mf_interaction', 'standard_mask_rmse'):.6f} | {gap(main, 'linucb_mf_interaction', 'pdf_literal_norm_rmse'):.6f} | {gap(main, 'linucb_mf_interaction', 'w_rmse'):.6f} | {gap(main, 'linucb_mf_interaction', 'cumulative_reward'):.6f} |

Forced-exp comparator gaps, DU-Net minus comparator:

| comparator | standard RMSE gap | PDF-literal RMSE gap | local weighted RMSE gap | cumulative reward gap |
|---|---:|---:|---:|---:|
| Linear UCB concat | {gap(forced, 'linucb_concat', 'standard_mask_rmse'):.6f} | {gap(forced, 'linucb_concat', 'pdf_literal_norm_rmse'):.6f} | {gap(forced, 'linucb_concat', 'w_rmse'):.6f} | {gap(forced, 'linucb_concat', 'cumulative_reward'):.6f} |
| Linear UCB MF | {gap(forced, 'linucb_mf_interaction', 'standard_mask_rmse'):.6f} | {gap(forced, 'linucb_mf_interaction', 'pdf_literal_norm_rmse'):.6f} | {gap(forced, 'linucb_mf_interaction', 'w_rmse'):.6f} | {gap(forced, 'linucb_mf_interaction', 'cumulative_reward'):.6f} |

## Reflection

The latest faithful backend promotion did not materially shrink DU-Net's own
absolute RMSE: standard RMSE moved by {standard_delta:.6f} versus the previous
user-feature/full-DLS/Schur v4 run. It did improve the paper-facing comparison
because DU-Net is lower than Linear UCB MF on standard and PDF-literal RMSE, and
the top-k Linear UCB concat comparison also favors DU-Net on RMSE-style metrics.

The weak point is now isolated rather than hidden: if Linear UCB concat is also
forced to use full-pool exponential sampling, it becomes lower than DU-Net on
standard RMSE by {abs(gap(forced, 'linucb_concat', 'standard_mask_rmse')):.6f}.
Because the paper text does not identify Linear UCB's exact sampling protocol,
this remains a protocol ambiguity, not a license to tune DU-Net further.

Backend strengthening had mixed side effects: cumulative reward changed by
{reward_delta:.6f}, while local weighted RMSE changed by {w_delta:.6f}. That is
why this branch should be treated as a fidelity confirmation, not a performance
breakthrough.

## Next Faithful Step

The next executable improvement should be triggered by one of four source-backed
artifacts: exact Figure 4a metric, exact MovieLens split/masks, exact DU-Net
backend/tuning details, or exact Linear UCB protocol. Once one arrives, run only
the minimal 3-seed diagnostic first, then promote to 20 seeds if it improves the
paper-facing gap without adding non-paper mechanisms.
"""
    return report


def main() -> None:
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    write_gate_table()
    REPORT_PATH.write_text(build_report(), encoding="utf-8")
    print(REPORT_PATH)
    print(TABLE_PATH)


if __name__ == "__main__":
    main()
