"""Build the next-trigger protocol for Figure 4a replication."""

from __future__ import annotations

from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
TABLE_DIR = ROOT / "outputs" / "tables"
REPORT_DIR = ROOT / "reports"

FINAL_SUMMARY = TABLE_DIR / "figure4a_final_package_summary.csv"
READINESS_AUDIT = TABLE_DIR / "figure4a_readiness_audit.csv"

OUT_CSV = TABLE_DIR / "figure4a_next_trigger_protocol.csv"
OUT_REPORT = REPORT_DIR / "figure4a_next_trigger_protocol.md"


def fmt(value: object, digits: int = 4) -> str:
    try:
        if pd.isna(value):
            return "nan"
        return f"{float(value):.{digits}f}"
    except (TypeError, ValueError):
        return str(value)


def trigger_rows() -> pd.DataFrame:
    return pd.DataFrame(
        [
            {
                "trigger": "Exact Figure 4a w-RMSE definition recovered",
                "minimum_input": "Weights, normalization, test mask, clipping, seed/cycle aggregation",
                "first_action": "Implement metric as an additional reported metric without replacing existing local metrics",
                "validation": "Re-evaluate saved/final predictions if possible; otherwise run seeds 0,1,2 only",
                "promote_to_20seed_if": "DU-Net-vs-Linear gap improves without making conventional/sigmoid contradictions worse",
            },
            {
                "trigger": "Author MovieLens split or initial/candidate masks recovered",
                "minimum_input": "Train/test split, initial observed set, candidate set, preprocessing/filtering, seed protocol",
                "first_action": "Create a source-faithful 3-seed config using the recovered masks",
                "validation": "Run DU-Net current, MF-centered Linear UCB proxy, and Myopic on seeds 0,1,2",
                "promote_to_20seed_if": "Primary local/paper metric gap improves by at least 0.005 and no reward collapse occurs",
            },
            {
                "trigger": "DU-Net entropy/DLS implementation recovered",
                "minimum_input": "Observational entropy estimator, DLS smoothing, network diffusion, feature normalization",
                "first_action": "Add a source-faithful DU-Net candidate beside the frozen current DU-Net",
                "validation": "Run seeds 0,1,2 with all Phase 1 metrics reported",
                "promote_to_20seed_if": "Candidate improves frozen DU-Net by at least 0.005 on the primary metric or materially reduces the remaining paper-target shortfall",
            },
            {
                "trigger": "Per-cycle lambda/sigma_t/p_t tuning protocol recovered",
                "minimum_input": "Inner train/acquisition/test construction, grid, loss, tie-breaks, retuning frequency",
                "first_action": "Replace the proxy adaptive tuner with the recovered protocol",
                "validation": "Run 1 seed first, then seeds 0,1,2 only if seed0 does not regress reward-weighted w-RMSE",
                "promote_to_20seed_if": "3-seed result improves current DU-Net and preserves reward advantage",
            },
            {
                "trigger": "Paper Linear UCB protocol recovered",
                "minimum_input": "Feature map, alpha/regularization, reward transform, update protocol",
                "first_action": "Add source-faithful Linear UCB as appendix comparator; keep existing proxy frozen",
                "validation": "Run seeds 0,1,2 against current DU-Net and Myopic",
                "promote_to_20seed_if": "Comparator change does not mask a DU-Net regression and clarifies the paper gap",
            },
        ]
    )


def markdown_table(rows: pd.DataFrame) -> str:
    lines = [
        "| trigger | first action | validation | 20-seed promotion rule |",
        "|---|---|---|---|",
    ]
    for row in rows.itertuples(index=False):
        lines.append(
            f"| {row.trigger} | {row.first_action} | {row.validation} | {row.promote_to_20seed_if} |"
        )
    return "\n".join(lines)


def write_report(rows: pd.DataFrame) -> None:
    final = pd.read_csv(FINAL_SUMMARY)
    readiness = pd.read_csv(READINESS_AUDIT)
    du = final[final["variant"] == "du_net"].iloc[0]
    linear = final[final["variant"] == "mf_linear_ucb_a002"].iloc[0]
    gap = float(linear.local_reward_weighted_w_rmse) - float(du.local_reward_weighted_w_rmse)
    ready = bool(readiness["exists"].all())
    report = f"""# Figure 4a Next-Trigger Protocol

Generated by `experiments/build_figure4a_next_trigger_protocol.py`.

## Current State

Local execution is closed and handoff readiness is `{str(ready).lower()}`.
Current 20-seed local reward-weighted gap is `{fmt(gap)}`:
DU-Net `{fmt(du.local_reward_weighted_w_rmse)}` versus MF-centered Linear UCB
proxy `{fmt(linear.local_reward_weighted_w_rmse)}`.

No local sweep is pending. The next run must be triggered by new source
information, not by another seed expansion or proxy grid.

## Trigger-To-Action Table

{markdown_table(rows)}

## Hard Stop Rules

- Do not run 20 seeds before a passing seeds `0,1,2` diagnostic.
- Do not promote a candidate that improves conventional RMSE by lowering reward
  acquisition and worsening reward-weighted w-RMSE.
- Do not relabel MF-centered Linear UCB proxy as exact paper Linear UCB unless
  the paper feature/update protocol is recovered.
- Do not choose a metric solely because it favors DU-Net.

## Active Next Step

Wait for source evidence or author clarification. When one trigger appears,
execute only the listed first action and validation path.
"""
    OUT_REPORT.write_text(report, encoding="utf-8")


def main() -> None:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    rows = trigger_rows()
    rows.to_csv(OUT_CSV, index=False)
    write_report(rows)
    print(f"Wrote {OUT_CSV}")
    print(f"Wrote {OUT_REPORT}")
    print(rows.to_string(index=False))


if __name__ == "__main__":
    main()
