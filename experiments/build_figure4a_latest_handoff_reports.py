from __future__ import annotations

import csv
from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
TABLE_DIR = ROOT / "outputs" / "tables"
REPORT_DIR = ROOT / "reports"

FINAL_SUMMARY = TABLE_DIR / "figure4a_final_package_summary.csv"
LATEST_GAPS = TABLE_DIR / "figure4a_latest_metric_reconciliation_gaps.csv"
NO_NETWORK_GATE = TABLE_DIR / "figure4a_no_network_fidelity_gate.csv"
EXP_GATE = TABLE_DIR / "figure4a_exp_fidelity_gate.csv"

PAPER_GAP = 1.814 - 1.788


def fmt(value: object, digits: int = 4) -> str:
    try:
        if pd.isna(value):
            return "nan"
        return f"{float(value):.{digits}f}"
    except (TypeError, ValueError):
        return str(value)


def write_csv(path: Path, rows: list[dict[str, object]]) -> None:
    with path.open("w", newline="", encoding="utf-8-sig") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def write_markdown(path: Path, content: str) -> None:
    path.write_text(content, encoding="utf-8-sig")


def markdown_table(rows: list[dict[str, object]]) -> str:
    columns = list(rows[0].keys())
    lines = [
        "| " + " | ".join(columns) + " |",
        "| " + " | ".join("---" for _ in columns) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(str(row[col]) for col in columns) + " |")
    return "\n".join(lines)


def load_context() -> dict[str, object]:
    final = pd.read_csv(FINAL_SUMMARY)
    gaps = pd.read_csv(LATEST_GAPS)
    no_network = pd.read_csv(NO_NETWORK_GATE).iloc[0]
    exp = pd.read_csv(EXP_GATE).iloc[0]

    du = final[final["variant"] == "du_net"].iloc[0]
    linear = final[final["variant"] == "mf_linear_ucb_a002"].iloc[0]
    myopic = final[final["variant"] == "myopic"].iloc[0]

    primary_gap = float(linear.linear_reward_norm_w_rmse - du.linear_reward_norm_w_rmse)
    myopic_gap = float(myopic.linear_reward_norm_w_rmse - du.linear_reward_norm_w_rmse)
    rmse_gap = float(linear.rmse - du.rmse)
    sigmoid_gap = gaps[
        (gaps["comparator"] == "mf_linear_ucb_a002")
        & (gaps["metric"] == "sigmoid_reward_w_rmse")
    ].iloc[0]

    return {
        "du": du,
        "linear": linear,
        "myopic": myopic,
        "primary_gap": primary_gap,
        "myopic_gap": myopic_gap,
        "rmse_gap": rmse_gap,
        "sigmoid_gap": float(sigmoid_gap.comparator_minus_du),
        "paper_share": 100.0 * primary_gap / PAPER_GAP,
        "no_network": no_network,
        "exp": exp,
    }


