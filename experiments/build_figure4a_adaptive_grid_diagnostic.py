"""Summarize Phase 3 adaptive-grid diagnostics for Figure 4a."""

from __future__ import annotations

from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
TABLE_DIR = ROOT / "outputs" / "tables"
REPORT_DIR = ROOT / "reports"

RUNS = {
    "ungarded_adaptive_grid_1seed": TABLE_DIR / "movielens_100k_svdpp_figure4a_adaptive_grid_1seed_metrics.csv",
    "guarded_adaptive_grid_1seed": TABLE_DIR / "movielens_100k_svdpp_figure4a_adaptive_grid_guarded_1seed_metrics.csv",
    "reward_floor_adaptive_grid_1seed": TABLE_DIR / "movielens_100k_svdpp_figure4a_adaptive_grid_reward_floor_1seed_metrics.csv",
}

OUT_CSV = TABLE_DIR / "figure4a_adaptive_grid_gate.csv"
OUT_PARAM_CSV = TABLE_DIR / "figure4a_adaptive_grid_param_frequency.csv"
OUT_REPORT = REPORT_DIR / "figure4a_adaptive_grid_diagnostic.md"


def fmt(value: object, digits: int = 4) -> str:
    try:
        if pd.isna(value):
            return "nan"
        return f"{float(value):.{digits}f}"
    except (TypeError, ValueError):
        return str(value)


def load_rows() -> tuple[pd.DataFrame, pd.DataFrame]:
    rows = []
    param_rows = []
    for run, path in RUNS.items():
        metrics = pd.read_csv(path)
        final = metrics.sort_values("cycle").groupby(["variant", "seed"], as_index=False).tail(1)
        current = final[final["variant"].str.contains("du_net_current")].iloc[0]
        linear = final[final["variant"].str.contains("mf_linear_ucb")].iloc[0]
        for row in final.itertuples(index=False):
            if "du_net_adaptive_grid" not in str(row.policy):
                continue
            rows.append(
                {
                    "run": run,
                    "variant": row.variant,
                    "w_rmse": float(row.w_rmse),
                    "w_rmse_delta_vs_current": float(row.w_rmse) - float(current.w_rmse),
                    "rmse": float(row.rmse),
                    "rmse_delta_vs_current": float(row.rmse) - float(current.rmse),
                    "sigmoid_reward_w_rmse": float(row.sigmoid_reward_w_rmse),
                    "cumulative_reward": float(row.cumulative_reward),
                    "reward_delta_vs_current": float(row.cumulative_reward) - float(current.cumulative_reward),
                    "linear_minus_adaptive_w_rmse_gap": float(linear.w_rmse) - float(row.w_rmse),
                    "promote_to_3seed": bool(float(row.w_rmse) <= float(current.w_rmse) - 0.005),
                }
            )
        adaptive = metrics[(metrics["policy"] == "du_net_adaptive_grid") & (metrics["cycle"] < metrics["cycle"].max())]
        freq = (
            adaptive.groupby(["adaptive_lambda_entropy", "sigma", "adaptive_diffusion_prob"])
            .size()
            .reset_index(name="cycles")
            .sort_values("cycles", ascending=False)
        )
        freq.insert(0, "run", run)
        param_rows.extend(freq.to_dict("records"))
    return pd.DataFrame(rows), pd.DataFrame(param_rows)


def markdown_table(rows: pd.DataFrame) -> str:
    lines = [
        "| run | w-RMSE | delta vs current | RMSE delta | reward delta | Linear gap | promote 3-seed |",
        "|---|---:|---:|---:|---:|---:|---|",
    ]
    for row in rows.itertuples(index=False):
        lines.append(
            f"| {row.run} | {fmt(row.w_rmse)} | {fmt(row.w_rmse_delta_vs_current)} | "
            f"{fmt(row.rmse_delta_vs_current)} | {fmt(row.reward_delta_vs_current, 1)} | "
            f"{fmt(row.linear_minus_adaptive_w_rmse_gap)} | {str(row.promote_to_3seed).lower()} |"
        )
    return "\n".join(lines)


def write_report(rows: pd.DataFrame, params: pd.DataFrame) -> None:
    top_params = params.sort_values(["run", "cycles"], ascending=[True, False]).groupby("run").head(5)
    param_lines = [
        "| run | lambda | sigma | diffusion p | cycles |",
        "|---|---:|---:|---:|---:|",
    ]
    for row in top_params.itertuples(index=False):
        param_lines.append(
            f"| {row.run} | {fmt(row.adaptive_lambda_entropy, 2)} | {fmt(row.sigma, 2)} | "
            f"{fmt(row.adaptive_diffusion_prob, 3)} | {int(row.cycles)} |"
        )
    promoted = rows[rows["promote_to_3seed"]]
    decision = (
        "No adaptive-grid variant is promoted to 3 seeds. The guarded version reduces damage but still "
        "underperforms the fixed current DU-Net on the Phase 1 primary metric."
        if promoted.empty
        else "At least one adaptive-grid variant passes the 3-seed promotion gate."
    )
    report = f"""# Figure 4a Adaptive-Grid Diagnostic

Generated by `experiments/build_figure4a_adaptive_grid_diagnostic.py`.

## Gate Table

{markdown_table(rows)}

## Parameter Frequency

{chr(10).join(param_lines)}

## Decision

{decision}

The adaptive route improves conventional RMSE, but it does so by accepting lower
reward and worse reward-weighted w-RMSE. This matches the Phase 2 pattern:
broader exploration helps full-test RMSE but hurts the Figure 4a reward-weighted
proxy. The next improvement should therefore not be a wider adaptive grid. It
should either enforce reward/entropy floors in the adaptive objective or move to
the comparator/reporting phase with the current fixed DU-Net as the best local
candidate.

CSV artifacts:

- `{OUT_CSV.relative_to(ROOT)}`
- `{OUT_PARAM_CSV.relative_to(ROOT)}`
"""
    OUT_REPORT.write_text(report, encoding="utf-8")


def main() -> None:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    rows, params = load_rows()
    rows.to_csv(OUT_CSV, index=False)
    params.to_csv(OUT_PARAM_CSV, index=False)
    write_report(rows, params)
    print(f"Wrote {OUT_CSV}")
    print(f"Wrote {OUT_PARAM_CSV}")
    print(f"Wrote {OUT_REPORT}")
    print(rows.to_string(index=False))


if __name__ == "__main__":
    main()
