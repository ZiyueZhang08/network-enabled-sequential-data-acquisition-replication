"""Record the no-author-source closure for the Figure 4a replication branch."""

from __future__ import annotations

import csv
from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
TABLE_DIR = ROOT / "outputs" / "tables"
REPORT_DIR = ROOT / "reports"

FINAL_SUMMARY = TABLE_DIR / "figure4a_final_package_summary.csv"
INTAKE_CHECK = TABLE_DIR / "source_trigger_intake_check.csv"

OUT_CSV = TABLE_DIR / "figure4a_no_author_source_closure.csv"
OUT_REPORT = REPORT_DIR / "figure4a_no_author_source_closure.md"

PAPER_GAP = 1.814 - 1.788


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8-sig") as file:
        return list(csv.DictReader(file))


def row_by(rows: list[dict[str, str]], key: str, value: str) -> dict[str, str]:
    for row in rows:
        if row.get(key) == value:
            return row
    raise KeyError(f"Missing {key}={value}")


def fmt(value: object, digits: int = 4) -> str:
    try:
        if pd.isna(value):
            return "nan"
        return f"{float(value):.{digits}f}"
    except (TypeError, ValueError):
        return str(value)


def build_rows() -> list[dict[str, str]]:
    final = pd.read_csv(FINAL_SUMMARY)
    intake = read_rows(INTAKE_CHECK)
    du = final[final["variant"] == "du_net"].iloc[0]
    linear = final[final["variant"] == "mf_linear_ucb_a002"].iloc[0]
    myopic = final[final["variant"] == "myopic"].iloc[0]
    gate = row_by(intake, "item", "rerun_gate")
    next_run = row_by(intake, "item", "next_executable_run")

    gap = float(linear.local_reward_weighted_w_rmse) - float(du.local_reward_weighted_w_rmse)
    myopic_gap = float(myopic.local_reward_weighted_w_rmse) - float(du.local_reward_weighted_w_rmse)
    share = 100.0 * gap / PAPER_GAP

    return [
        {
            "item": "author_source_status",
            "status": "unavailable",
            "evidence": "User confirmed that author source code is not available.",
            "decision": "Do not keep author-source recovery as an active execution branch.",
        },
        {
            "item": "current_result",
            "status": "partial_reproduction",
            "evidence": (
                f"DU-Net {fmt(du.local_reward_weighted_w_rmse)} vs "
                f"MF-centered Linear UCB proxy {fmt(linear.local_reward_weighted_w_rmse)}; "
                f"gap {fmt(gap)}; paper-gap share {fmt(share, 1)}%."
            ),
            "decision": "Report as directionally positive under the local reward-weighted proxy, not exact replication.",
        },
        {
            "item": "threshold_status",
            "status": "below_secondary_threshold",
            "evidence": f"Linear-minus-DU gap {fmt(gap)} is below the +0.010 secondary threshold.",
            "decision": "Do not promote new 20-seed work without a non-code source trigger.",
        },
        {
            "item": "myopic_context",
            "status": "du_net_slightly_better",
            "evidence": f"Myopic-minus-DU local w-RMSE gap is {fmt(myopic_gap)}.",
            "decision": "Keep Myopic in the final package as a sanity comparator.",
        },
        {
            "item": "rerun_gate",
            "status": gate["status"],
            "evidence": gate["evidence"],
            "decision": gate["decision"],
        },
        {
            "item": "next_executable_run",
            "status": next_run["status"],
            "evidence": next_run["evidence"],
            "decision": "With no author source, this stays blocked unless exact metric/split/protocol details arrive from non-code evidence.",
        },
        {
            "item": "allowed_next_improvement",
            "status": "reporting_or_non_code_evidence_only",
            "evidence": "Local metric, entropy, adaptive tuning, comparator, and 20-seed package are complete.",
            "decision": "Improve the written caveat/evidence package, or reopen only with exact w-RMSE, split/mask, tuning, or Linear UCB protocol details.",
        },
    ]


def write_csv(rows: list[dict[str, str]]) -> None:
    with OUT_CSV.open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def markdown_table(rows: list[dict[str, str]]) -> str:
    lines = ["| item | status | evidence | decision |", "|---|---|---|---|"]
    for row in rows:
        lines.append(f"| {row['item']} | {row['status']} | {row['evidence']} | {row['decision']} |")
    return "\n".join(lines)


def write_report(rows: list[dict[str, str]]) -> None:
    current = row_by(rows, "item", "current_result")
    gate = row_by(rows, "item", "rerun_gate")
    report = f"""# Figure 4a No-Author-Source Closure

Generated by `experiments/build_figure4a_no_author_source_closure.py`.

## Current Decision

Author source code is unavailable. Under that constraint, the local Figure 4a
branch is computationally closed rather than merely waiting for a code drop.

Current result: {current['evidence']}

Rerun gate: `{gate['status']}`.

## Closure Table

{markdown_table(rows)}

## Reflection

The useful work has already separated signal from noise: local reward-weighted
and high-rating evaluations preserve a small DU-Net advantage, while full
conventional RMSE does not. Observational entropy and adaptive tuning diagnostics
did not pass promotion gates. Without author code, another local proxy sweep
would mostly test our assumptions rather than the paper's implementation.

## Next Step

Do not run another model experiment. The next useful work is either:

- polish the final report around the partial-reproduction claim and its limits;
- reopen with non-code source evidence such as the exact w-RMSE definition,
  exact MovieLens split/masks, per-cycle tuning protocol, or paper Linear UCB
  feature/update protocol;
- if no such evidence appears, treat exact Figure 4a replication as unavailable
  from public artifacts and cite the final local result as a caveated proxy.

CSV artifact: `{OUT_CSV.relative_to(ROOT)}`.
"""
    OUT_REPORT.write_text(report, encoding="utf-8")


def main() -> None:
    TABLE_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    rows = build_rows()
    write_csv(rows)
    write_report(rows)
    print(f"Wrote {OUT_CSV}")
    print(f"Wrote {OUT_REPORT}")


if __name__ == "__main__":
    main()
