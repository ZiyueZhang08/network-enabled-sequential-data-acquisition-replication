"""Build a concise submission packet for the Figure 4a handoff."""

from __future__ import annotations

import csv
from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
TABLE_DIR = ROOT / "outputs" / "tables"
REPORT_DIR = ROOT / "reports"

FINAL_SUMMARY = TABLE_DIR / "figure4a_final_package_summary.csv"
CLAIM_FREEZE = TABLE_DIR / "figure4a_claim_freeze.csv"
HANDOFF_INDEX = TABLE_DIR / "figure4a_handoff_index.csv"
QUALITY_GATE = TABLE_DIR / "figure4a_delivery_quality_gate.csv"
AUTHOR_EMAIL = REPORT_DIR / "author_source_request_email.md"

OUT_CSV = TABLE_DIR / "figure4a_submission_packet.csv"
OUT_REPORT = REPORT_DIR / "figure4a_submission_packet.md"

PAPER_GAP = 1.814 - 1.788


def fmt(value: object, digits: int = 4) -> str:
    try:
        if pd.isna(value):
            return "nan"
        return f"{float(value):.{digits}f}"
    except (TypeError, ValueError):
        return str(value)


def metric_rows(final: pd.DataFrame) -> list[dict[str, str]]:
    du = final[final["variant"] == "du_net"].iloc[0]
    linear = final[final["variant"] == "mf_linear_ucb_a002"].iloc[0]
    myopic = final[final["variant"] == "myopic"].iloc[0]
    gap = float(linear.linear_reward_norm_w_rmse) - float(du.linear_reward_norm_w_rmse)
    return [
        {
            "item": "primary_gap",
            "value": fmt(gap),
            "evidence": (
                f"DU-Net {fmt(du.linear_reward_norm_w_rmse)} vs "
                f"MF-centered Linear UCB proxy {fmt(linear.linear_reward_norm_w_rmse)}"
            ),
            "decision": "Primary paper-like proxy is directionally consistent with Figure 4a.",
        },
        {
            "item": "paper_gap_share",
            "value": f"{100.0 * gap / PAPER_GAP:.1f}%",
            "evidence": f"Local gap {fmt(gap)} vs paper visual gap estimate {PAPER_GAP:.3f}",
            "decision": "Strong partial reproduction, not exact replication.",
        },
        {
            "item": "myopic_gap",
            "value": fmt(float(myopic.linear_reward_norm_w_rmse) - float(du.linear_reward_norm_w_rmse)),
            "evidence": (
                f"DU-Net {fmt(du.linear_reward_norm_w_rmse)} vs "
                f"Myopic {fmt(myopic.linear_reward_norm_w_rmse)}"
            ),
            "decision": "Sanity comparator does not overturn the DU-Net proxy advantage.",
        },
        {
            "item": "conventional_rmse_caveat",
            "value": fmt(float(linear.rmse) - float(du.rmse)),
            "evidence": f"DU-Net RMSE {fmt(du.rmse)} vs Linear UCB proxy RMSE {fmt(linear.rmse)}",
            "decision": "Must report that conventional RMSE still favors the comparator.",
        },
        {
            "item": "source_request",
            "value": str(AUTHOR_EMAIL.relative_to(ROOT)),
            "evidence": "Copy-ready request uses the frozen 0.0207 result and current caveats.",
            "decision": "Use this as the next external action if exact replication is required.",
        },
    ]


def write_csv(rows: list[dict[str, str]]) -> None:
    with OUT_CSV.open("w", newline="", encoding="utf-8-sig") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def claim_lines(claims: pd.DataFrame, claim_type: str) -> str:
    selected = claims[claims["claim_type"] == claim_type]
    lines = []
    for row in selected.itertuples(index=False):
        lines.append(f"- {row.claim} Evidence: {row.evidence}")
    return "\n".join(lines)


def submit_lines(index: pd.DataFrame) -> str:
    keep = {
        "Final conclusion",
        "Submission bundle",
        "Final Chinese delivery",
        "Delivery quality gate",
        "Artifact readiness",
        "Author request email",
        "Reopen protocol",
        "Artifact checksums",
    }
    selected = index[index["purpose"].isin(keep)].sort_values("order")
    lines = []
    for row in selected.itertuples(index=False):
        lines.append(f"- `{row.artifact}` - {row.use_when}")
    return "\n".join(lines)


def metric_table(rows: list[dict[str, str]]) -> str:
    lines = [
        "| item | value | evidence | decision |",
        "|---|---:|---|---|",
    ]
    for row in rows:
        lines.append(f"| {row['item']} | `{row['value']}` | {row['evidence']} | {row['decision']} |")
    return "\n".join(lines)


def write_report(rows: list[dict[str, str]]) -> None:
    claims = pd.read_csv(CLAIM_FREEZE)
    index = pd.read_csv(HANDOFF_INDEX)
    quality = pd.read_csv(QUALITY_GATE)
    quality_ok = bool((quality["status"] == "pass").all())

    report = f"""# Figure 4a Submission Packet

Generated by `experiments/build_figure4a_submission_packet.py`.

## Submission Decision

Current status: `ready_for_caveated_submission`.

Quality gate passed: `{str(quality_ok).lower()}`.

The result should be submitted as a strong partial reproduction of the Figure 4a
ordering under a transparent reward-weighted proxy. It should not be submitted
as an exact DU-Net Figure 4a replication.

## Headline Metrics

{metric_table(rows)}

## Files To Submit First

{submit_lines(index)}

## Allowed Claims

{claim_lines(claims, "allowed")}

## Forbidden Claims

{claim_lines(claims, "forbidden")}

## External Source Request

Use `reports/author_source_request_email.md` when asking for source-backed
details. The request is synchronized to the frozen `0.0207` primary gap and the
`79.5%` paper-gap share.

## Reopen Rule

Do not run another broad local tuning sweep. Reopen only if source-backed
evidence arrives for exact w-RMSE, split/masks, DU-Net entropy/DLS/tuning, or
paper Linear UCB protocol. The first run after any trigger is seeds `0,1,2`,
with promotion to 20 seeds only after the trigger-specific gate passes.
"""
    OUT_REPORT.write_text(report, encoding="utf-8-sig")


def main() -> None:
    TABLE_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    rows = metric_rows(pd.read_csv(FINAL_SUMMARY))
    write_csv(rows)
    write_report(rows)
    print(f"Wrote {OUT_CSV}")
    print(f"Wrote {OUT_REPORT}")
    for row in rows:
        print(f"{row['item']}: {row['value']} | {row['decision']}")


if __name__ == "__main__":
    main()
