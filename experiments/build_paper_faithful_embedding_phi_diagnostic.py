"""Summarize the z-normalization and MovieLens node-embedding diagnostic."""

from __future__ import annotations

import csv
from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
REPORT_PATH = ROOT / "reports" / "paper_faithful_embedding_phi_diagnostic_20260709.md"
TABLE_PATH = ROOT / "outputs" / "tables" / "paper_faithful_embedding_phi_diagnostic_20260709.csv"

MAIN_METRICS = ROOT / "outputs" / "tables" / "paper_faithful_movielens_rank20_ep20_v4_20seeds_metrics.csv"
ELPH_SUMMARY = ROOT / "outputs" / "tables" / "paper_faithful_movielens_elph_role_3seeds_final_summary.csv"

METRICS = [
    "standard_mask_rmse",
    "pdf_literal_norm_rmse",
    "w_rmse",
    "reward_tail_proxy_rmse",
    "cumulative_reward",
]


def f6(value: float) -> str:
    return f"{float(value):.6f}"


def mainline_seed_subset() -> dict[str, float]:
    metrics = pd.read_csv(MAIN_METRICS)
    final = (
        metrics[(metrics["variant"] == "paper_faithful_dunet") & (metrics["seed"].isin([0, 1, 2]))]
        .sort_values("cycle")
        .groupby(["variant", "seed"], as_index=False)
        .tail(1)
    )
    return {metric: float(final[metric].mean()) for metric in METRICS}


def summary_row(path: Path) -> dict[str, float]:
    with path.open(newline="", encoding="utf-8") as f:
        row = next(csv.DictReader(f))
    return {metric: float(row[metric]) for metric in METRICS}


def write_table(main: dict[str, float], elph: dict[str, float]) -> None:
    TABLE_PATH.parent.mkdir(parents=True, exist_ok=True)
    rows = []
    for metric in METRICS:
        delta = elph[metric] - main[metric]
        rows.append(
            {
                "metric": metric,
                "mainline_seed0_2": main[metric],
                "elph_role_seed0_2": elph[metric],
                "elph_minus_mainline": delta,
                "direction": "lower_is_better" if metric != "cumulative_reward" else "higher_is_better",
            }
        )
    with TABLE_PATH.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "metric",
                "mainline_seed0_2",
                "elph_role_seed0_2",
                "elph_minus_mainline",
                "direction",
            ],
        )
        writer.writeheader()
        writer.writerows(rows)


def build_report() -> str:
    main = mainline_seed_subset()
    elph = summary_row(ELPH_SUMMARY)
    write_table(main, elph)
    lines = [
        "# Embedding and phi diagnostic",
        "",
        "Generated by `experiments/build_paper_faithful_embedding_phi_diagnostic.py`.",
        "",
        "## Paper Check",
        "",
        "The paper text around Section 4.2.1 states that both the reward and the",
        "information value are z-normalized. This supports the existing score path:",
        "`zscore(reward) + lambda * zscore(entropy_like_value)`. I therefore did not",
        "replace z-normalization with a new scaling rule.",
        "",
        "The remaining paper-faithful question was `u_sn`: Section 3.2 and Algorithm",
        "DU-Net describe pre-computed node embeddings from the social network, while",
        "the current MovieLens mainline uses auxiliary user features directly. I ran",
        "one narrow diagnostic using the existing ELPH-role structural proxy over the",
        "MovieLens KNN graph. This is a fidelity probe, not a broad embedding sweep.",
        "",
        "## Same-seed Result",
        "",
        "Both rows use seeds 0-2, rank20/ep20 SVD++, full-user Gaussian DLS, full-pool",
        "Schur entropy, MovieLens `p=0`, dynamic lambda/sigma tuning, and DU-Net",
        "exponential sampling.",
        "",
        "| branch | standard RMSE | PDF-literal RMSE | local w-RMSE | reward-tail RMSE | cumulative reward |",
        "|---|---:|---:|---:|---:|---:|",
        (
            f"| mainline user-feature `u_sn` | {f6(main['standard_mask_rmse'])} | "
            f"{f6(main['pdf_literal_norm_rmse'])} | {f6(main['w_rmse'])} | "
            f"{f6(main['reward_tail_proxy_rmse'])} | {f6(main['cumulative_reward'])} |"
        ),
        (
            f"| ELPH-role graph proxy `u_sn` | {f6(elph['standard_mask_rmse'])} | "
            f"{f6(elph['pdf_literal_norm_rmse'])} | {f6(elph['w_rmse'])} | "
            f"{f6(elph['reward_tail_proxy_rmse'])} | {f6(elph['cumulative_reward'])} |"
        ),
        "",
        "ELPH-role minus mainline:",
        "",
        "| metric | delta | direction |",
        "|---|---:|---|",
    ]
    for metric in METRICS:
        direction = "lower is better" if metric != "cumulative_reward" else "higher is better"
        lines.append(f"| {metric} | {elph[metric] - main[metric]:.6f} | {direction} |")
    lines.extend(
        [
            "",
            "## Reflection",
            "",
            "The ELPH-role proxy is more aligned with the paper's wording about",
            "pre-computed social node embeddings, but it does not improve the local",
            "Figure 4a objective. Standard RMSE worsens by "
            f"{elph['standard_mask_rmse'] - main['standard_mask_rmse']:.6f}, and local w-RMSE worsens by "
            f"{elph['w_rmse'] - main['w_rmse']:.6f}. It slightly improves cumulative reward by "
            f"{elph['cumulative_reward'] - main['cumulative_reward']:.6f}, but that is not the left-panel Figure 4a gap.",
            "",
            "I therefore keep `configs/paper_faithful_movielens_elph_role.json` as a",
            "documented source-faithful diagnostic, but I do not promote it to 20 seeds",
            "or replace the current user-feature `u_sn` mainline.",
            "",
            "## Next Step",
            "",
            "The next useful improvement should be source-backed rather than another",
            "local embedding proxy. A true author ELPH embedding, exact Monti/MovieLens",
            "split, exact w-RMSE implementation, or exact Linear UCB protocol would",
            "unlock a new minimal 3-seed diagnostic. Without one of those, the current",
            "best RMSE mainline remains user-feature `u_sn` with direct Eq. 3.6 Schur",
            "entropy.",
        ]
    )
    return "\n".join(lines) + "\n"


def main() -> None:
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(build_report(), encoding="utf-8")
    print(REPORT_PATH)
    print(TABLE_PATH)


if __name__ == "__main__":
    main()
