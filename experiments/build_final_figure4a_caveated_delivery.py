"""Build the final caveated Figure 4a delivery report."""

from __future__ import annotations

import csv
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TABLE_DIR = ROOT / "outputs" / "tables"
REPORT_DIR = ROOT / "reports"

TARGET_CSV = TABLE_DIR / "figure4a_final_target_report.csv"
OUT_CSV = TABLE_DIR / "final_figure4a_caveated_delivery.csv"
OUT_REPORT = REPORT_DIR / "final_figure4a_caveated_delivery.md"


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open("r", newline="", encoding="utf-8") as file:
        return list(csv.DictReader(file))


def row(rows: list[dict[str, str]], comparison: str) -> dict[str, str]:
    for item in rows:
        if item["comparison"] == comparison:
            return item
    raise KeyError(comparison)


def f(value: str) -> float:
    return float(value)


def fmt(value: float, digits: int = 4) -> str:
    return f"{value:.{digits}f}"


def build_rows() -> list[dict[str, str]]:
    target = read_rows(TARGET_CSV)
    paper = row(target, "paper_visual_w_rmse")
    local = row(target, "local_reward_weighted_w_rmse")
    full = row(target, "rmse_all")
    high = row(target, "rmse_high_rating_ge4")
    low = row(target, "rmse_low_rating_le3")
    sigmoid = row(target, "sigmoid_reward_w_rmse")

    return [
        {
            "claim_area": "paper_target",
            "status": "visual_estimate",
            "du_net": fmt(f(paper["du_net"]), 3),
            "linear_ucb": fmt(f(paper["linear_ucb"]), 3),
            "linear_minus_du": fmt(f(paper["linear_minus_du"]), 3),
            "claim": "Paper Figure 4a visually favors DU-Net over Linear UCB.",
        },
        {
            "claim_area": "local_reward_weighted",
            "status": "direction_matches",
            "du_net": fmt(f(local["du_net"])),
            "linear_ucb": fmt(f(local["linear_ucb"])),
            "linear_minus_du": fmt(f(local["linear_minus_du"])),
            "claim": "Local reward-weighted w-RMSE recovers the paper direction, but not the paper scale.",
        },
        {
            "claim_area": "local_full_rmse",
            "status": "direction_does_not_match",
            "du_net": fmt(f(full["du_net"])),
            "linear_ucb": fmt(f(full["linear_ucb"])),
            "linear_minus_du": fmt(f(full["linear_minus_du"])),
            "claim": "Full-test conventional RMSE favors Linear UCB, so this is not an exact Figure 4a reproduction.",
        },
        {
            "claim_area": "local_high_rating_region",
            "status": "mechanism_support",
            "du_net": fmt(f(high["du_net"])),
            "linear_ucb": fmt(f(high["linear_ucb"])),
            "linear_minus_du": fmt(f(high["linear_minus_du"])),
            "claim": "High-rating test regions favor DU-Net, supporting the reward-region mechanism.",
        },
        {
            "claim_area": "local_low_rating_region",
            "status": "mechanism_limit",
            "du_net": fmt(f(low["du_net"])),
            "linear_ucb": fmt(f(low["linear_ucb"])),
            "linear_minus_du": fmt(f(low["linear_minus_du"])),
            "claim": "Low-rating test regions favor Linear UCB, explaining the full-test RMSE reversal.",
        },
        {
            "claim_area": "sigmoid_reward_weighted",
            "status": "near_tie",
            "du_net": fmt(f(sigmoid["du_net"])),
            "linear_ucb": fmt(f(sigmoid["linear_ucb"])),
            "linear_minus_du": fmt(f(sigmoid["linear_minus_du"]), 6),
            "claim": "Paper-like sigmoid weighting is effectively tied at 20 seeds.",
        },
    ]


def write_csv(rows: list[dict[str, str]]) -> None:
    with OUT_CSV.open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def markdown_table(rows: list[dict[str, str]]) -> str:
    lines = [
        "| claim area | status | DU-Net | Linear UCB | Linear - DU | claim |",
        "|---|---|---:|---:|---:|---|",
    ]
    for item in rows:
        lines.append(
            f"| {item['claim_area']} | {item['status']} | {item['du_net']} | "
            f"{item['linear_ucb']} | {item['linear_minus_du']} | {item['claim']} |"
        )
    return "\n".join(lines)


def write_report(rows: list[dict[str, str]]) -> None:
    report = f"""# Final Figure 4a Caveated Delivery

Generated by `experiments/build_final_figure4a_caveated_delivery.py`.

## Final Status

The Figure 4a reproduction is complete as a local caveated result. It should be
reported as a strong partial reproduction, not as a paper-exact DU-Net
replication.

The strongest truthful claim is:

> The local DU-Net-style model is consistent with the paper's DU-Net-over-Linear
> UCB relationship in reward-weighted and high-rating evaluation regions, but it
> does not reproduce the paper's absolute Figure 4a w-RMSE scale or the
> DU-Net-over-Linear-UCB ordering under full-test conventional RMSE.

## Reportable Numbers

{markdown_table(rows)}

## What To Claim

- Compare against the local MF-centered Linear UCB row as the best recovered
  Linear-UCB-style comparator.
- Say the paper direction is recovered under local reward-weighted w-RMSE:
  DU-Net 0.8250 versus Linear UCB 0.8333.
- Say the mechanism is supported in high-rating regions:
  DU-Net 0.6587 versus Linear UCB 0.6671.
- State the distance clearly: local DU-Net reward-weighted w-RMSE is about
  0.461x of the paper visual DU-Net endpoint.

## What Not To Claim

- Do not claim exact Figure 4a reproduction.
- Do not claim the paper's full-test RMSE ordering is recovered.
- Do not claim exact SVD++ backend, w-RMSE weighting, per-step tuning, or Linear
  UCB feature construction.
- Do not infer the two unresolved benchmark labels from dependency repositories.

## Next Trigger

Further execution should wait for one of these triggers:

1. author code, supplement, split files, or exact configs;
2. a precise source definition of Figure 4a w-RMSE;
3. explicit approval to add validated external mechanism dependencies and run a
   smallest faithful 3-seed diagnostic.

Without one of those, the next action is reporting, not more experimentation.

CSV artifact: `{OUT_CSV.relative_to(ROOT)}`.
"""
    OUT_REPORT.write_text(report, encoding="utf-8")


def main() -> None:
    TABLE_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    rows = build_rows()
    write_csv(rows)
    write_report(rows)
    print(f"Wrote {OUT_CSV}")
    print(f"Wrote {OUT_REPORT}")


if __name__ == "__main__":
    main()
